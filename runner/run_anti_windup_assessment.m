function limits = localPlotLimits(values)
    lower = min([values; 0]);
    upper = max([values; 0]);
    span = upper - lower;
    if span == 0
        span = 1;
    end
    padding = 0.08 * span;
    limits = [lower - padding, upper + padding];
end

function percent = localPercentChange(enabled, disabled)
    percent = NaN(size(enabled));
    nonzero = enabled ~= 0 & isfinite(enabled) & isfinite(disabled);
    percent(nonzero) = 100 * ...
        (disabled(nonzero) - enabled(nonzero)) ./ abs(enabled(nonzero));
end

function value = localMeanOrNaN(values)
    finiteValues = values(isfinite(values));
    if isempty(finiteValues)
        value = NaN;
    else
        value = mean(finiteValues);
    end
end

function value = localMaxOrNaN(values)
    finiteValues = values(isfinite(values));
