function [conditionMetricTable, comparisonTable, runData] = ...
        run_anti_windup_assessment(varargin)
%RUN_ANTI_WINDUP_ASSESSMENT SUP-AW-001 dynamic effectiveness assessment.
%
%   Compares the same repeated +15/-15 rps reversal sequence under:
%     A) AW ON:  Gain2 = 1, Kas = Kis / Kps
%     B) AW OFF: Gain2 = 0, Kas = Kis / Kps
%
%   Gain2 = 0 is a comparison condition used only to assess anti-windup
%   effectiveness. Kas and all other controller parameters remain fixed.
%
%   Name-value options:
%     'PlateauDuration_s'  Duration of each plateau (default: 2)
%     'RepeatCount'        Number of +15/-15 pairs (default: 3)
%
%   PlateauDuration_s and RepeatCount are test sequence execution
%   parameters, not product performance requirements. This supplemental
%   assessment reports quantitative differences only and creates no
%   Compliance Oracle, PASS/FAIL threshold, or acceptance criterion.

    parser = inputParser;
    parser.FunctionName = mfilename;
    addParameter(parser, 'PlateauDuration_s', 2, @localPositiveScalar);
    addParameter(parser, 'RepeatCount', 3, ...
        @(x) isnumeric(x) && isreal(x) && isscalar(x) && ...
        isfinite(x) && x >= 1 && x == floor(x));
    parse(parser, varargin{:});
    options = parser.Results;

    plateauDuration_s = double(options.PlateauDuration_s);
    repeatCount = double(options.RepeatCount);
    totalSegmentCount = 2 * repeatCount;
    stopTime_s = totalSegmentCount * plateauDuration_s;
    pulsePeriod_s = 2 * plateauDuration_s;

    runnerDirectory = fileparts(mfilename('fullpath'));
    repositoryRoot = fileparts(runnerDirectory);
    modelDirectory = fullfile(repositoryRoot, 'model');
    modelName = 'AS2308_MIL_Baseline_v3';
    modelFile = fullfile(modelDirectory, [modelName, '.slx']);
    parameterScript = fullfile( ...
        modelDirectory, 'AS2308_calculate_pi_control_cc.m');

    assert(isfile(modelFile), 'Model file not found: %s', modelFile);
    assert(isfile(parameterScript), ...
        'Parameter script not found: %s', parameterScript);

    run(parameterScript);
    baselineKas = Kis / Kps;
    simulationVariables = struct( ...
        'ts', ts, 'Vdc', Vdc, 'Kps', Kps, 'Kis', Kis, ...
        'Kas', baselineKas, ...
        'SpeedRef_cmd', 0);

    modelWasLoaded = bdIsLoaded(modelName);
    load_system(modelFile);
    originalDirtyState = get_param(modelName, 'Dirty');

    assert(strcmp(get_param(modelName, 'SolverType'), 'Fixed-step'), ...
        'Stored model SolverType must be Fixed-step.');
    assert(strcmp(get_param(modelName, 'Solver'), 'ode4'), ...
        'Stored model Solver must be ode4.');
    assert(strcmp(get_param(modelName, 'FixedStep'), 'ts'), ...
        'Stored model FixedStep must be ts.');
    assert(ts == 0.0004, 'Expected ts = 0.0004 s.');

    integratorPath = [modelName, '/PI Speed Controller/Integrator'];
    integratorPorts = get_param(integratorPath, 'PortHandles');
    integratorOutport = integratorPorts.Outport(1);
    loggingState = struct( ...
        'PortHandle', integratorOutport, ...
        'DataLogging', get_param(integratorOutport, 'DataLogging'), ...
        'DataLoggingNameMode', ...
            get_param(integratorOutport, 'DataLoggingNameMode'), ...
        'DataLoggingName', get_param(integratorOutport, 'DataLoggingName'));
    set_param(integratorOutport, ...
        'DataLogging', 'on', ...
        'DataLoggingNameMode', 'Custom', ...
        'DataLoggingName', 'integrator_output');
    restoreModel = onCleanup(@() localRestoreModel( ...
        modelName, modelWasLoaded, originalDirtyState, loggingState)); %#ok<NASGU>

    pulseGenerator = localFindUniqueBlock( ...
        modelName, 'BlockType', 'DiscretePulseGenerator');
    referenceOffset = [modelName, '/Constant2'];
    referenceSwitch = [modelName, '/Manual Switch'];
    gain2Path = [modelName, '/PI Speed Controller/Gain2'];

    condition_id = ["AW_ON"; "AW_OFF"];
    condition_description = [ ...
        "AW ON: Gain2 = 1, Kas = Kis / Kps"; ...
        "AW OFF comparison: Gain2 = 0, Kas = Kis / Kps"];
    gain2_value = [1; 0];
    kas_value = repmat(baselineKas, 2, 1);
    numberOfConditions = numel(condition_id);
    effective_aw_feedback_enabled = gain2_value ~= 0 & kas_value ~= 0;

    max_abs_integrator_output = zeros(numberOfConditions, 1);
    max_raw_pi_output_v = zeros(numberOfConditions, 1);
    min_raw_pi_output_v = zeros(numberOfConditions, 1);
    max_vcmd_v = zeros(numberOfConditions, 1);
    min_vcmd_v = zeros(numberOfConditions, 1);
    saturation_sample_count = zeros(numberOfConditions, 1);
    saturation_duration_s = zeros(numberOfConditions, 1);
    max_abs_integrator_during_saturation = NaN(numberOfConditions, 1);
    post_saturation_event_count = zeros(numberOfConditions, 1);
    mean_abs_integrator_at_saturation_exit = NaN(numberOfConditions, 1);
    mean_abs_integrator_at_plateau_end = NaN(numberOfConditions, 1);
    mean_abs_integrator_change_after_saturation = NaN(numberOfConditions, 1);
    post_saturation_abs_integrator_area = NaN(numberOfConditions, 1);
    mean_integrator_deviation_at_saturation_exit = ...
        NaN(numberOfConditions, 1);
    post_saturation_integrator_deviation_area = ...
        NaN(numberOfConditions, 1);
    runData = repmat(struct( ...
        'condition_id', "", ...
        'kas_value', NaN, ...
        'gain2_value', NaN, ...
        'samples', table()), numberOfConditions, 1);

    fprintf('\nSUP-AW-001 Anti-Windup Dynamic Effectiveness Assessment\n');
    fprintf('Model: %s\n', modelName);
    fprintf('Kas fixed at Kis/Kps = %.12g for both conditions\n', baselineKas);
    fprintf(['Plateau duration: %.6g s; repeat count: %d ', ...
        '(test execution parameters)\n'], plateauDuration_s, repeatCount);
    fprintf(['No Compliance Oracle or PASS/FAIL criterion is applied.\n\n']);

    for conditionIndex = 1:numberOfConditions
        simulationInput = Simulink.SimulationInput(modelName);
        variableNames = fieldnames(simulationVariables);
        for variableIndex = 1:numel(variableNames)
            variableName = variableNames{variableIndex};
            simulationInput = simulationInput.setVariable( ...
                variableName, simulationVariables.(variableName));
        end
        simulationInput = simulationInput.setBlockParameter( ...
            gain2Path, 'Gain', sprintf('%.17g', gain2_value(conditionIndex)));

        simulationInput = simulationInput.setBlockParameter( ...
            pulseGenerator, 'Amplitude', '2');
        simulationInput = simulationInput.setBlockParameter( ...
            pulseGenerator, 'Period', sprintf('%.17g', pulsePeriod_s));
        simulationInput = simulationInput.setBlockParameter( ...
            pulseGenerator, 'PulseWidth', '50');
        simulationInput = simulationInput.setBlockParameter( ...
            pulseGenerator, 'PhaseDelay', '0');
        simulationInput = simulationInput.setBlockParameter( ...
            referenceOffset, 'Value', '1');
        simulationInput = simulationInput.setBlockParameter( ...
            referenceSwitch, 'CurrentSetting', '1');
        simulationInput = simulationInput.setModelParameter( ...
            'StopTime', sprintf('%.17g', stopTime_s), ...
            'SignalLogging', 'on', ...
            'SignalLoggingName', 'logsout', ...
            'SignalLoggingSaveFormat', 'Dataset', ...
            'ReturnWorkspaceOutputs', 'on');

        simulationOutput = sim(simulationInput);
        loggedSignals = simulationOutput.get('logsout');
        referenceSignal = localGetLoggedSignal(loggedSignals, 'reference');
        motorSpeedSignal = localGetLoggedSignal(loggedSignals, 'motorspeed');
        integratorSignal = localGetLoggedSignal( ...
            loggedSignals, 'integrator_output');
        rawPiSignal = localGetLoggedSignal(loggedSignals, 'raw_pi_output');
        vcmdSignal = localGetLoggedSignal(loggedSignals, 'Vcmd');

        time = double(motorSpeedSignal.Time(:));
        motorspeed = localSignalData(motorSpeedSignal);
        reference = localAlignSignal(referenceSignal, time);
        integratorOutput = localAlignSignal(integratorSignal, time);
        rawPiOutput = localAlignSignal(rawPiSignal, time);
        vcmd = localAlignSignal(vcmdSignal, time);

        saturationSamples = rawPiOutput > Vdc | rawPiOutput < -Vdc;
        max_abs_integrator_output(conditionIndex) = ...
            max(abs(integratorOutput));
        max_raw_pi_output_v(conditionIndex) = max(rawPiOutput);
        min_raw_pi_output_v(conditionIndex) = min(rawPiOutput);
        max_vcmd_v(conditionIndex) = max(vcmd);
        min_vcmd_v(conditionIndex) = min(vcmd);
        saturation_sample_count(conditionIndex) = sum(saturationSamples);
        saturation_duration_s(conditionIndex) = ...
            trapz(time, double(saturationSamples));
        if any(saturationSamples)
            max_abs_integrator_during_saturation(conditionIndex) = ...
                max(abs(integratorOutput(saturationSamples)));
        end

        recoveryMetrics = localMeasurePostSaturationRecovery( ...
            time, integratorOutput, saturationSamples, plateauDuration_s);
        post_saturation_event_count(conditionIndex) = ...
            recoveryMetrics.event_count;
        mean_abs_integrator_at_saturation_exit(conditionIndex) = ...
            recoveryMetrics.mean_abs_at_exit;
        mean_abs_integrator_at_plateau_end(conditionIndex) = ...
            recoveryMetrics.mean_abs_at_plateau_end;
        mean_abs_integrator_change_after_saturation(conditionIndex) = ...
            recoveryMetrics.mean_abs_change;
        post_saturation_abs_integrator_area(conditionIndex) = ...
            recoveryMetrics.total_abs_area;
        mean_integrator_deviation_at_saturation_exit(conditionIndex) = ...
            recoveryMetrics.mean_deviation_at_exit;
        post_saturation_integrator_deviation_area(conditionIndex) = ...
            recoveryMetrics.total_deviation_area;

        runData(conditionIndex).condition_id = condition_id(conditionIndex);
        runData(conditionIndex).kas_value = kas_value(conditionIndex);
        runData(conditionIndex).gain2_value = gain2_value(conditionIndex);
        runData(conditionIndex).samples = table( ...
            time, reference, motorspeed, integratorOutput, rawPiOutput, ...
            vcmd, saturationSamples, ...
            'VariableNames', { ...
            'time_s', 'reference_rps', 'motorspeed_rps', ...
            'integrator_output', 'raw_pi_output_v', 'Vcmd_v', ...
            'saturation_active'});

        fprintf(['%s | Gain2 %.0f | Kas %.12g | max|integrator| %.12g | ', ...
            'raw PI [%+.12g, %+.12g] V | Vcmd [%+.12g, %+.12g] V | ', ...
            'saturation samples %d | duration %.12g s\n'], ...
            condition_id(conditionIndex), gain2_value(conditionIndex), ...
            kas_value(conditionIndex), ...
            max_abs_integrator_output(conditionIndex), ...
            min_raw_pi_output_v(conditionIndex), ...
            max_raw_pi_output_v(conditionIndex), ...
            min_vcmd_v(conditionIndex), max_vcmd_v(conditionIndex), ...
            saturation_sample_count(conditionIndex), ...
            saturation_duration_s(conditionIndex));
    end

    conditionMetricTable = table( ...
        condition_id, condition_description, kas_value, ...
        gain2_value, effective_aw_feedback_enabled, ...
        max_abs_integrator_output, max_raw_pi_output_v, min_raw_pi_output_v, ...
        max_vcmd_v, min_vcmd_v, saturation_sample_count, ...
        saturation_duration_s, max_abs_integrator_during_saturation, ...
        post_saturation_event_count, ...
        mean_abs_integrator_at_saturation_exit, ...
        mean_abs_integrator_at_plateau_end, ...
        mean_abs_integrator_change_after_saturation, ...
        post_saturation_abs_integrator_area, ...
        mean_integrator_deviation_at_saturation_exit, ...
        post_saturation_integrator_deviation_area);

    metric = [ ...
        "max_abs_integrator_output"; ...
        "max_raw_pi_output_v"; ...
        "min_raw_pi_output_v"; ...
        "max_vcmd_v"; ...
        "min_vcmd_v"; ...
        "saturation_sample_count"; ...
        "saturation_duration_s"; ...
        "max_abs_integrator_during_saturation"; ...
        "post_saturation_event_count"; ...
        "mean_abs_integrator_at_saturation_exit"; ...
        "mean_abs_integrator_at_plateau_end"; ...
        "mean_abs_integrator_change_after_saturation"; ...
        "post_saturation_abs_integrator_area"; ...
        "mean_integrator_deviation_at_saturation_exit"; ...
        "post_saturation_integrator_deviation_area"];
    aw_enabled_value = [ ...
        max_abs_integrator_output(1); ...
        max_raw_pi_output_v(1); ...
        min_raw_pi_output_v(1); ...
        max_vcmd_v(1); ...
        min_vcmd_v(1); ...
        saturation_sample_count(1); ...
        saturation_duration_s(1); ...
        max_abs_integrator_during_saturation(1); ...
        post_saturation_event_count(1); ...
        mean_abs_integrator_at_saturation_exit(1); ...
        mean_abs_integrator_at_plateau_end(1); ...
        mean_abs_integrator_change_after_saturation(1); ...
        post_saturation_abs_integrator_area(1); ...
        mean_integrator_deviation_at_saturation_exit(1); ...
        post_saturation_integrator_deviation_area(1)];
    aw_disabled_value = [ ...
        max_abs_integrator_output(2); ...
        max_raw_pi_output_v(2); ...
        min_raw_pi_output_v(2); ...
        max_vcmd_v(2); ...
        min_vcmd_v(2); ...
        saturation_sample_count(2); ...
        saturation_duration_s(2); ...
        max_abs_integrator_during_saturation(2); ...
        post_saturation_event_count(2); ...
        mean_abs_integrator_at_saturation_exit(2); ...
        mean_abs_integrator_at_plateau_end(2); ...
        mean_abs_integrator_change_after_saturation(2); ...
        post_saturation_abs_integrator_area(2); ...
        mean_integrator_deviation_at_saturation_exit(2); ...
        post_saturation_integrator_deviation_area(2)];
    disabled_minus_enabled = aw_disabled_value - aw_enabled_value;
    comparisonTable = table( ...
        metric, aw_enabled_value, aw_disabled_value, ...
        disabled_minus_enabled);

    fprintf('\nCondition metrics:\n');
    disp(conditionMetricTable);
    fprintf('AW disabled minus AW enabled comparison:\n');
    disp(comparisonTable);
    fprintf(['NOTE: Gain2 = 0 is a comparison condition only. ', ...
        'Kas remains fixed at Kis/Kps in both conditions. ', ...
        'These measurements do not define a new product requirement.\n']);
end

function metrics = localMeasurePostSaturationRecovery( ...
        time, integratorOutput, saturationSamples, plateauDuration_s)
% Measure recovery from each saturation exit to the end of that plateau.
% These descriptive metrics do not introduce a recovery threshold.
    exitIndices = find(saturationSamples(1:end-1) & ...
        ~saturationSamples(2:end)) + 1;

    metrics = struct( ...
        'event_count', numel(exitIndices), ...
        'mean_abs_at_exit', NaN, ...
        'mean_abs_at_plateau_end', NaN, ...
        'mean_abs_change', NaN, ...
        'total_abs_area', NaN, ...
        'mean_deviation_at_exit', NaN, ...
        'total_deviation_area', NaN);

    if isempty(exitIndices)
        return;
    end

    absAtExit = zeros(numel(exitIndices), 1);
    absAtPlateauEnd = zeros(numel(exitIndices), 1);
    absArea = zeros(numel(exitIndices), 1);
    deviationAtExit = zeros(numel(exitIndices), 1);
    deviationArea = zeros(numel(exitIndices), 1);

    for eventIndex = 1:numel(exitIndices)
        exitIndex = exitIndices(eventIndex);
        plateauNumber = floor(time(exitIndex) / plateauDuration_s) + 1;
        plateauEndTime = min( ...
            plateauNumber * plateauDuration_s, time(end));
        plateauEndIndex = find(time <= plateauEndTime, 1, 'last');

        absAtExit(eventIndex) = abs(integratorOutput(exitIndex));
        absAtPlateauEnd(eventIndex) = ...
            abs(integratorOutput(plateauEndIndex));
        recoveryIndices = exitIndex:plateauEndIndex;
        absArea(eventIndex) = trapz( ...
            time(recoveryIndices), abs(integratorOutput(recoveryIndices)));
        plateauEndValue = integratorOutput(plateauEndIndex);
        deviationAtExit(eventIndex) = abs( ...
            integratorOutput(exitIndex) - plateauEndValue);
        deviationArea(eventIndex) = trapz(time(recoveryIndices), ...
            abs(integratorOutput(recoveryIndices) - plateauEndValue));
    end

    metrics.mean_abs_at_exit = mean(absAtExit);
    metrics.mean_abs_at_plateau_end = mean(absAtPlateauEnd);
    metrics.mean_abs_change = mean(absAtPlateauEnd - absAtExit);
    metrics.total_abs_area = sum(absArea);
    metrics.mean_deviation_at_exit = mean(deviationAtExit);
    metrics.total_deviation_area = sum(deviationArea);
end

function data = localSignalData(signal)
    data = double(squeeze(signal.Data));
    data = data(:);
end

function value = localAlignSignal(signal, targetTime)
    signalTime = double(signal.Time(:));
    signalData = localSignalData(signal);

    if isequal(signalTime, targetTime)
        value = signalData;
    else
        value = interp1( ...
            signalTime, signalData, targetTime, 'previous', 'extrap');
    end
end

function signal = localGetLoggedSignal(loggedSignals, signalName)
    signalElement = loggedSignals.get(signalName);
    if isempty(signalElement)
        error('run_anti_windup_assessment:MissingSignal', ...
            'Logged signal "%s" was not found.', signalName);
    end
    signal = signalElement.Values;
end

function blockPath = localFindUniqueBlock(modelName, varargin)
    blocks = find_system(modelName, ...
        'LookUnderMasks', 'all', 'FollowLinks', 'on', varargin{:});
    if numel(blocks) ~= 1
        error('run_anti_windup_assessment:UnexpectedBlockCount', ...
            'Expected one matching block, found %d.', numel(blocks));
    end
    blockPath = blocks{1};
end

function valid = localPositiveScalar(value)
    valid = isnumeric(value) && isreal(value) && isscalar(value) && ...
        isfinite(value) && value > 0;
end

function localRestoreModel( ...
        modelName, modelWasLoaded, dirtyState, loggingState)
    if ~bdIsLoaded(modelName)
        return;
    end

    set_param(loggingState.PortHandle, ...
        'DataLogging', loggingState.DataLogging, ...
        'DataLoggingNameMode', loggingState.DataLoggingNameMode, ...
        'DataLoggingName', loggingState.DataLoggingName);
    set_param(modelName, 'Dirty', dirtyState);

    if ~modelWasLoaded
        close_system(modelName, 0);
    end
end
