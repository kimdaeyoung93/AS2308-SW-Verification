function silSmokeResult = run_sil_b2b_smoke_test()
%RUN_SIL_B2B_SMOKE_TEST Run one derived-model Normal/top-model SIL smoke test.
%
%   SILSMOKERESULT = RUN_SIL_B2B_SMOKE_TEST() executes only SIL-SMOKE-001:
%   the frozen MTC-002 / IT-001 +2 rps waveform from 0 through 1 s. The
%   derived verification model is run once in Normal mode and once in
%   top-model Software-in-the-Loop (SIL) mode.
%
%   Required observations are the two discrete root outputs. Continuous
%   internal signal logging is deliberately not used as the primary
%   observation mechanism. Difference metrics are informational only; this
%   smoke test defines no numerical equivalence tolerance or PASS/FAIL.

    protocolVersion = "v1.1 Frozen";
    scenarioID = "SIL-SMOKE-001";
    frozenScenario = "MTC-002 / IT-001";
    expectedSourceHash = ...
        "4A7FDC070506CA641ACBD2C3EFEA2FEF71DDCC150CA3FC1F20F191B8B998ED4D";
    expectedDerivedHash = ...
        "0223B483023B87DE70FA440558AF651DF4B21DCD9B8C7095772A6CDFAB18D565";
    sourceModelName = 'AS2308_MIL_Baseline_v3';
    derivedModelName = 'AS2308_SIL_B2B_Verification_v1';

    runnerDirectory = fileparts(mfilename('fullpath'));
    repositoryRoot = fileparts(runnerDirectory);
    sourceFile = fullfile(repositoryRoot, 'model', ...
        [sourceModelName, '.slx']);
    derivedFile = fullfile(repositoryRoot, 'model', 'verification', ...
        [derivedModelName, '.slx']);
    protocolFile = fullfile(repositoryRoot, 'docs', ...
        '04_SIL_BackToBack_Protocol_v1.1.md');
    parameterScript = fullfile(repositoryRoot, 'model', ...
        'AS2308_calculate_pi_control_cc.m');
    manualRunnerFile = fullfile(runnerDirectory, ...
        'run_manual_mil_suite.m');
    buildRoot = fullfile(repositoryRoot, 'build', 'sil_b2b_smoke');
    cacheDirectory = fullfile(buildRoot, 'cache');
    codegenDirectory = fullfile(buildRoot, 'codegen');
    resultDirectory = fullfile(repositoryRoot, 'results', ...
        'sil_b2b_smoke_v1');
    summaryFile = fullfile(resultDirectory, 'smoke_summary.csv');
    metricsFile = fullfile(resultDirectory, 'signal_metrics.csv');
    metadataFile = fullfile(resultDirectory, 'metadata.txt');
    generatedMatFile = fullfile(repositoryRoot, ...
        [derivedModelName, '.mat']);
    generatedMatExistedBefore = isfile(generatedMatFile);

    localEnsureDirectory(cacheDirectory);
    localEnsureDirectory(codegenDirectory);
    localEnsureDirectory(resultDirectory);

    summary = localEmptySummary();
    summary.ProtocolVersion = protocolVersion;
    summary.ScenarioID = scenarioID;
    summary.SourceScenario = frozenScenario;
    summary.Status = "EXECUTION_ERROR";
    summary.BuildArtifactPath = string(buildRoot);
    metrics = localEmptyMetricTable(scenarioID);
    runData = struct('normal', struct(), 'sil', struct(), ...
        'normal_console', "", 'sil_console', "");
    sourceHashBefore = "NOT_CHECKED";
    derivedHashBefore = "NOT_CHECKED";
    parameters = struct('Kps', NaN, 'Kis', NaN, 'Kas', NaN, ...
        'Vdc', NaN, 'ts', NaN);
    compilerDescription = localCompilerDescription();
    normalWarning = struct('identifier', "", 'text', "");
    silWarning = struct('identifier', "", 'text', "");

    try
        localAssertFile(sourceFile, 'Frozen source model');
        localAssertFile(derivedFile, 'Derived verification model');
        localAssertFile(protocolFile, 'Frozen SIL Protocol v1.1');
        localAssertFile(parameterScript, 'Controller parameter script');
        localAssertFile(manualRunnerFile, 'Frozen Manual MIL runner');

        sourceHashBefore = localFileSha256(sourceFile);
        derivedHashBefore = localFileSha256(derivedFile);
        summary.SourceHashBefore = sourceHashBefore;
        summary.DerivedHashBefore = derivedHashBefore;
        assert(strcmpi(sourceHashBefore, expectedSourceHash), ...
            'run_sil_b2b_smoke_test:SourceHashMismatch', ...
            'Frozen source SHA-256 mismatch.');
        assert(strcmpi(derivedHashBefore, expectedDerivedHash), ...
            'run_sil_b2b_smoke_test:DerivedHashMismatch', ...
            'Derived model SHA-256 mismatch.');

        run(parameterScript);
        parameters = struct('Kps', Kps, 'Kis', Kis, 'Kas', Kas, ...
            'Vdc', Vdc, 'ts', ts);
        localAssertFrozenParameters(parameters);
        localAssertFrozenWaveformDefinition(manualRunnerFile);
        [inputTime, inputValues] = localSmokeWaveform(parameters.ts);

        derivedWasLoaded = bdIsLoaded(derivedModelName);
        if ~derivedWasLoaded
            load_system(derivedFile);
        end
        modelCleanup = onCleanup(@() localRestoreModelLoadState( ...
            derivedModelName, derivedWasLoaded));
        assert(strcmp(get_param(derivedModelName, 'Dirty'), 'off'), ...
            'run_sil_b2b_smoke_test:DirtyDerivedModel', ...
            'Derived model must be clean before smoke execution.');
        localAssertStoredConfiguration(derivedModelName, parameters.ts);
        localAssertRootInterface(derivedModelName, parameters.ts);

        currentFileGenConfig = Simulink.fileGenControl('getConfig');
        originalFileGenConfig = struct( ...
            'CacheFolder', currentFileGenConfig.CacheFolder, ...
            'CodeGenFolder', currentFileGenConfig.CodeGenFolder, ...
            'CodeGenFolderStructure', ...
                currentFileGenConfig.CodeGenFolderStructure);
        fileGenCleanup = onCleanup(@() localRestoreFileGeneration( ...
            originalFileGenConfig));
        Simulink.fileGenControl('set', ...
            'CacheFolder', cacheDirectory, ...
            'CodeGenFolder', codegenDirectory, ...
            'createDir', true);

        normalInput = localSimulationInput(derivedModelName, ...
            parameters, inputTime, inputValues, 'normal'); %#ok<NASGU>
        lastwarn('', '');
        normalTimer = tic;
        normalConsole = evalc('normalOutput = sim(normalInput);');
        summary.NormalElapsed_s = toc(normalTimer);
        [normalWarningText, normalWarningID] = lastwarn;
        normalWarning = struct('identifier', string(normalWarningID), ...
            'text', string(normalWarningText));
        runData.normal_console = string(normalConsole);
        normalSignals = localRootOutputs(normalOutput);
        runData.normal = normalSignals;
        summary.NormalExecutionSuccess = true;
        summary.SampledVcmdCollectedNormal = true;
        summary.SampledMotorSpeedCollectedNormal = true;

        silInput = localSimulationInput(derivedModelName, ...
            parameters, inputTime, inputValues, ...
            'Software-in-the-Loop (SIL)'); %#ok<NASGU>
        lastwarn('', '');
        silTimer = tic;
        silConsole = evalc('silOutput = sim(silInput);');
        summary.SILBuildAndExecutionElapsed_s = toc(silTimer);
        [silWarningText, silWarningID] = lastwarn;
        silWarning = struct('identifier', string(silWarningID), ...
            'text', string(silWarningText));
        runData.sil_console = string(silConsole);
        silSignals = localRootOutputs(silOutput);
        runData.sil = silSignals;
        summary.SILExecutableExecutionSuccess = true;
        summary.SILApplicationStarted = true;
        summary.SILApplicationTerminated = true;
        summary.SampledVcmdCollectedSIL = true;
        summary.SampledMotorSpeedCollectedSIL = true;

        localRelocateGeneratedRuntimeMat( ...
            generatedMatFile, generatedMatExistedBefore, buildRoot);

        artifactEvidence = localBuildEvidence(buildRoot, silConsole);
        summary.CodeGenerationStarted = ...
            artifactEvidence.code_generation_started;
        summary.CodeGenerationSucceeded = ...
            artifactEvidence.code_generation_succeeded;
        summary.SILExecutableGenerated = ...
            artifactEvidence.sil_executable_generated;
        % Successful top-model SIL execution proves that its build and
        % executable launch completed, even if a temporary executable is
        % removed by the platform after termination.
        summary.SILBuildSuccess = ...
            summary.SILExecutableExecutionSuccess && ...
            summary.CodeGenerationSucceeded;

        summary = localRecordGrid(summary, normalSignals, silSignals);
        metrics = localDifferenceMetrics( ...
            scenarioID, normalSignals, silSignals);

        allRequiredOutputs = ...
            summary.SampledVcmdCollectedNormal && ...
            summary.SampledMotorSpeedCollectedNormal && ...
            summary.SampledVcmdCollectedSIL && ...
            summary.SampledMotorSpeedCollectedSIL;
        allRequiredTimes = localHasRequiredTimes(normalSignals) && ...
            localHasRequiredTimes(silSignals);
        if summary.NormalExecutionSuccess && summary.SILBuildSuccess && ...
                summary.SILExecutableExecutionSuccess && ...
                allRequiredOutputs && allRequiredTimes
            summary.Status = "EXECUTION_OK";
        end
    catch exception
        summary.Status = "EXECUTION_ERROR";
        summary.ErrorIdentifier = string(exception.identifier);
        summary.ErrorMessage = string(exception.message);
    end

    sourceHashAfter = localFileSha256IfPresent(sourceFile);
    derivedHashAfter = localFileSha256IfPresent(derivedFile);
    summary.SourceHashAfter = sourceHashAfter;
    summary.DerivedHashAfter = derivedHashAfter;
    summary.SourceHashUnchanged = ...
        sourceHashBefore ~= "NOT_CHECKED" && ...
        strcmpi(sourceHashBefore, sourceHashAfter) && ...
        strcmpi(sourceHashAfter, expectedSourceHash);
    summary.DerivedHashUnchanged = ...
        derivedHashBefore ~= "NOT_CHECKED" && ...
        strcmpi(derivedHashBefore, derivedHashAfter) && ...
        strcmpi(derivedHashAfter, expectedDerivedHash);

    [summary, warningSummary] = localRecordWarnings( ...
        summary, runData, normalWarning, silWarning);
    if ~(summary.SourceHashUnchanged && summary.DerivedHashUnchanged)
        summary.Status = "EXECUTION_ERROR";
        if strlength(summary.ErrorMessage) == 0
            summary.ErrorIdentifier = ...
                "run_sil_b2b_smoke_test:IntegrityCheckFailed";
            summary.ErrorMessage = ...
                "Source or derived model hash changed during execution.";
        end
    end
    if bdIsLoaded(derivedModelName) && ...
            ~strcmp(get_param(derivedModelName, 'Dirty'), 'off')
        summary.Status = "EXECUTION_ERROR";
        summary.ErrorIdentifier = ...
            "run_sil_b2b_smoke_test:DerivedModelBecameDirty";
        summary.ErrorMessage = ...
            "Derived model became dirty; it was not saved.";
    end

    summaryTable = struct2table(summary);
    writetable(summaryTable, summaryFile);
    writetable(metrics, metricsFile);
    localWriteMetadata(metadataFile, summary, parameters, ...
        compilerDescription, warningSummary, buildRoot, ...
        sourceFile, derivedFile);

    silSmokeResult = struct( ...
        'summary', summaryTable, ...
        'signal_metrics', metrics, ...
        'run_data', runData, ...
        'summary_file', string(summaryFile), ...
        'metrics_file', string(metricsFile), ...
        'metadata_file', string(metadataFile));

    fprintf('\nSIL B2B smoke test — %s\n', scenarioID);
    fprintf('Status: %s\n', summary.Status);
    fprintf('Normal execution: %s\n', localBooleanText( ...
        summary.NormalExecutionSuccess));
    fprintf('SIL build/execution: %s / %s\n', ...
        localBooleanText(summary.SILBuildSuccess), ...
        localBooleanText(summary.SILExecutableExecutionSuccess));
    fprintf('Root outputs collected (Normal/SIL): %s / %s\n', ...
        localBooleanText(summary.SampledVcmdCollectedNormal && ...
            summary.SampledMotorSpeedCollectedNormal), ...
        localBooleanText(summary.SampledVcmdCollectedSIL && ...
            summary.SampledMotorSpeedCollectedSIL));
    fprintf('Sample count (Normal/SIL): %g / %g\n', ...
        summary.NormalSampleCount, summary.SILSampleCount);
    fprintf('Time-grid equal: %s\n', ...
        localBooleanText(summary.TimeGridEqual));
    fprintf('Source SHA before/after: %s / %s\n', ...
        summary.SourceHashBefore, summary.SourceHashAfter);
    fprintf('Derived SHA before/after: %s / %s\n', ...
        summary.DerivedHashBefore, summary.DerivedHashAfter);
    fprintf('No numerical equivalence PASS/FAIL decision was made.\n\n');

    clear fileGenCleanup;
    clear modelCleanup;
end

function simulationInput = localSimulationInput( ...
        modelName, parameters, inputTime, inputValues, simulationMode)
    simulationInput = Simulink.SimulationInput(modelName);
    names = fieldnames(parameters);
    for index = 1:numel(names)
        simulationInput = simulationInput.setVariable( ...
            names{index}, parameters.(names{index}));
    end
    inputDataset = Simulink.SimulationData.Dataset;
    inputSeries = timeseries(inputValues, inputTime);
    inputSeries.Name = 'SpeedRef_rps';
    inputDataset = inputDataset.addElement(inputSeries, 'SpeedRef_rps');
    simulationInput = simulationInput.setExternalInput(inputDataset);
    simulationInput = simulationInput.setModelParameter( ...
        'SimulationMode', simulationMode, ...
        'StopTime', '1', ...
        'SignalLogging', 'off', ...
        'SaveOutput', 'on', ...
        'OutputSaveName', 'yout', ...
        'SaveFormat', 'Dataset', ...
        'SaveTime', 'on', ...
        'TimeSaveName', 'tout', ...
        'ReturnWorkspaceOutputs', 'on');
end

function signals = localRootOutputs(simulationOutput)
    yout = simulationOutput.get('yout');
    assert(isa(yout, 'Simulink.SimulationData.Dataset'), ...
        'run_sil_b2b_smoke_test:InvalidRootOutput', ...
        'Root output yout is not a Dataset.');
    assert(yout.numElements == 2, ...
        'run_sil_b2b_smoke_test:RootOutputCountMismatch', ...
        'Expected two root outputs, found %d.', yout.numElements);
    % The frozen structural audit establishes Outport 1 and Outport 2.
    signals = struct( ...
        'Vcmd', localSignal(yout.getElement(1), 'sampled_Vcmd'), ...
        'MotorSpeed', localSignal( ...
            yout.getElement(2), 'sampled_MotorSpeed'));
end

function signal = localSignal(datasetElement, expectedName)
    values = datasetElement.Values;
    signal = struct( ...
        'name', string(expectedName), ...
        'time', double(values.Time(:)), ...
        'data', double(squeeze(values.Data)));
    signal.data = signal.data(:);
    assert(~isempty(signal.time) && ~isempty(signal.data), ...
        'run_sil_b2b_smoke_test:EmptyRootSignal', ...
        '%s is empty.', expectedName);
    assert(numel(signal.time) == numel(signal.data), ...
        'run_sil_b2b_smoke_test:SignalLengthMismatch', ...
        '%s time/data lengths differ.', expectedName);
    assert(all(isfinite(signal.time)) && all(isfinite(signal.data)), ...
        'run_sil_b2b_smoke_test:NonFiniteRootSignal', ...
        '%s contains NaN or Inf.', expectedName);
    assert(all(diff(signal.time) > 0), ...
        'run_sil_b2b_smoke_test:NonMonotonicRootTime', ...
        '%s time is not strictly increasing.', expectedName);
end

function summary = localRecordGrid(summary, normalSignals, silSignals)
    assert(isequal(normalSignals.Vcmd.time, ...
        normalSignals.MotorSpeed.time), ...
        'run_sil_b2b_smoke_test:NormalRootGridMismatch', ...
        'Normal root outputs do not share one time grid.');
    assert(isequal(silSignals.Vcmd.time, silSignals.MotorSpeed.time), ...
        'run_sil_b2b_smoke_test:SILRootGridMismatch', ...
        'SIL root outputs do not share one time grid.');
    normalTime = normalSignals.Vcmd.time;
    silTime = silSignals.Vcmd.time;
    summary.NormalSampleCount = numel(normalTime);
    summary.SILSampleCount = numel(silTime);
    summary.NormalStartTime_s = normalTime(1);
    summary.NormalStopTime_s = normalTime(end);
    summary.SILStartTime_s = silTime(1);
    summary.SILStopTime_s = silTime(end);
    summary.TimeGridEqual = isequal(normalTime, silTime);
end

function metrics = localDifferenceMetrics( ...
        scenarioID, normalSignals, silSignals)
    names = ["sampled_Vcmd", "sampled_MotorSpeed"];
    units = ["V", "rps"];
    fields = ["Vcmd", "MotorSpeed"];
    rows = repmat(localEmptyMetric(), numel(names), 1);
    for index = 1:numel(names)
        row = localEmptyMetric();
        row.ScenarioID = scenarioID;
        row.SignalName = names(index);
        row.Unit = units(index);
        normalSignal = normalSignals.(fields(index));
        silSignal = silSignals.(fields(index));
        row.NormalSampleCount = numel(normalSignal.data);
        row.SILSampleCount = numel(silSignal.data);
        row.NormalFirstSample = normalSignal.data(1);
        row.NormalLastSample = normalSignal.data(end);
        row.SILFirstSample = silSignal.data(1);
        row.SILLastSample = silSignal.data(end);
        row.TimeGridEqual = isequal(normalSignal.time, silSignal.time);
        if row.TimeGridEqual && ...
                numel(normalSignal.data) == numel(silSignal.data)
            difference = normalSignal.data - silSignal.data;
            row.MaxAbsDiff = max(abs(difference));
            row.RmsDiff = sqrt(mean(difference .^ 2));
            row.DifferingSampleCount = sum( ...
                normalSignal.data ~= silSignal.data);
            row.Status = "EXECUTION_OK";
            row.Notes = ["Informational only; no numerical ", ...
                "equivalence tolerance or PASS/FAIL is defined."];
        else
            row.Status = "NOT_EVALUATED";
            row.Notes = ["Difference not calculated because the ", ...
                "time grids or sample counts differ; no interpolation ", ...
                "was used."];
        end
        rows(index) = row;
    end
    metrics = struct2table(rows);
end

function [summary, warningSummary] = localRecordWarnings( ...
        summary, runData, normalWarning, silWarning)
    combinedConsole = lower(runData.normal_console + newline + ...
        runData.sil_console);
    combinedWarningText = lower(normalWarning.text + newline + ...
        silWarning.text);
    unsupportedContinuous = ...
        contains(combinedConsole, "unsupported sample time: continuous") || ...
        contains(combinedWarningText, ...
            "unsupported sample time: continuous");
    warningOccurred = strlength(normalWarning.text) > 0 || ...
        strlength(silWarning.text) > 0 || ...
        contains(combinedConsole, "warning:") || ...
        contains(combinedConsole, "warning ");
    requiredOutputsCollected = ...
        summary.SampledVcmdCollectedNormal && ...
        summary.SampledMotorSpeedCollectedNormal && ...
        summary.SampledVcmdCollectedSIL && ...
        summary.SampledMotorSpeedCollectedSIL;
    if unsupportedContinuous && requiredOutputsCollected
        classification = "LEGACY_OR_INTERNAL_LOGGING_ONLY";
    elseif unsupportedContinuous
        classification = "REQUIRED_ROOT_OUTPUT_COLLECTION_IMPACTED";
    elseif warningOccurred
        classification = "OTHER_WARNING";
    else
        classification = "NONE";
    end
    summary.LoggingWarningOccurred = warningOccurred;
    summary.UnsupportedContinuousWarning = unsupportedContinuous;
    summary.WarningClassification = classification;
    summary.NormalWarningIdentifier = normalWarning.identifier;
    summary.NormalWarningText = localOneLine(normalWarning.text);
    summary.SILWarningIdentifier = silWarning.identifier;
    summary.SILWarningText = localOneLine(silWarning.text);
    warningSummary = struct( ...
        'normal_identifier', normalWarning.identifier, ...
        'normal_text', localOneLine(normalWarning.text), ...
        'sil_identifier', silWarning.identifier, ...
        'sil_text', localOneLine(silWarning.text), ...
        'unsupported_continuous', unsupportedContinuous, ...
        'classification', classification);
end

function evidence = localBuildEvidence(buildRoot, silConsole)
    codeFiles = dir(fullfile(buildRoot, '**', '*.c'));
    executableFiles = dir(fullfile(buildRoot, '**', '*.exe'));
    lowerConsole = lower(string(silConsole));
    consoleStart = contains(lowerConsole, 'code generation') || ...
        contains(lowerConsole, 'generating code') || ...
        contains(lowerConsole, 'building');
    evidence = struct( ...
        'code_generation_started', consoleStart || ~isempty(codeFiles), ...
        'code_generation_succeeded', ~isempty(codeFiles), ...
        'sil_executable_generated', ~isempty(executableFiles));
end

function [time, values] = localSmokeWaveform(sampleTime)
    assert(sampleTime == 0.0004, ...
        'run_sil_b2b_smoke_test:UnexpectedSampleTime', ...
        'Frozen smoke scenario requires ts = 0.0004 s.');
    sampleCount = round(1 / sampleTime);
    time = (0:sampleCount)' * sampleTime;
    values = 2 * ones(size(time));
    assert(time(1) == 0 && time(end) == 1);
    assert(numel(time) == 2501);
    assert(all(values == 2));
end

function localAssertFrozenWaveformDefinition(manualRunnerFile)
    source = string(regexprep(fileread(manualRunnerFile), '\s+', ' '));
    anchors = [ ...
        "constantReferences = [16.75; -16.75; 2; -2; 15; -15];"; ...
        "constantReferences(runIndex), 1);"; ...
        "'SpeedRef_cmd', reference_rps);" ];
    for index = 1:numel(anchors)
        assert(contains(source, anchors(index)), ...
            'run_sil_b2b_smoke_test:FrozenWaveformDefinitionChanged', ...
            'Frozen MTC-002 definition changed. Missing: %s', ...
            anchors(index));
    end
end

function localAssertStoredConfiguration(modelName, sampleTime)
    assert(strcmp(get_param(modelName, 'SolverType'), 'Fixed-step'));
    assert(strcmp(get_param(modelName, 'Solver'), 'ode4'));
    assert(strcmp(get_param(modelName, 'FixedStep'), 'ts'));
    assert(strcmp(get_param(modelName, 'SystemTargetFile'), 'grt.tlc'));
    assert(strcmp(get_param(modelName, 'TargetLang'), 'C'));
    assert(sampleTime == 0.0004);
end

function localAssertRootInterface(modelName, sampleTime)
    assert(strcmp(get_param([modelName, '/SpeedRef_rps'], ...
        'BlockType'), 'Inport'));
    assert(strcmp(get_param([modelName, '/sampled_Vcmd'], ...
        'BlockType'), 'Outport'));
    assert(strcmp(get_param([modelName, '/sampled_MotorSpeed'], ...
        'BlockType'), 'Outport'));
    assert(strcmp(get_param([modelName, '/Observe_Vcmd_ZOH'], ...
        'BlockType'), 'ZeroOrderHold'));
    assert(strcmp(get_param([modelName, '/Observe_MotorSpeed_ZOH'], ...
        'BlockType'), 'ZeroOrderHold'));
    assert(strcmp(get_param([modelName, '/Observe_Vcmd_ZOH'], ...
        'SampleTime'), 'ts'));
    assert(strcmp(get_param([modelName, '/Observe_MotorSpeed_ZOH'], ...
        'SampleTime'), 'ts'));
    assert(sampleTime == 0.0004);
end

function localAssertFrozenParameters(parameters)
    expectedKps = (2 * pi * 40) / 2185.96;
    expectedKis = 17.76 * expectedKps;
    assert(parameters.ts == 0.0004);
    assert(parameters.Vdc == 12);
    assert(parameters.Kps == expectedKps);
    assert(parameters.Kis == expectedKis);
    assert(parameters.Kas == expectedKis / expectedKps);
end

function present = localHasRequiredTimes(signals)
    present = ~isempty(signals.Vcmd.time) && ...
        ~isempty(signals.MotorSpeed.time);
end

