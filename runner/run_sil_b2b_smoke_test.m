function localWriteMetadata(filePath, summary, parameters, ...
        compilerDescription, warnings, buildRoot, sourceFile, derivedFile)
    fileIdentifier = fopen(filePath, 'wt');
    if fileIdentifier < 0
        error('run_sil_b2b_smoke_test:MetadataOpenFailed', ...
            'Could not open metadata file: %s', filePath);
    end
    closeFile = onCleanup(@() fclose(fileIdentifier));
    fprintf(fileIdentifier, 'Protocol: %s\n', summary.ProtocolVersion);
    fprintf(fileIdentifier, 'Scenario: %s (%s)\n', ...
        summary.ScenarioID, summary.SourceScenario);
