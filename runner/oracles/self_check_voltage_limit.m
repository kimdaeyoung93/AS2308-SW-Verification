function results = self_check_voltage_limit()
%SELF_CHECK_VOLTAGE_LIMIT Check pass and both violation directions.

    time = (0:0.1:0.4).';

    within_limits = evaluate_voltage_limit( ...
        time, [-12; -6; 0; 6; 12]);
    upper_violation = evaluate_voltage_limit( ...
        time, [-12; 0; 6; 12; 12.01]);
    lower_violation = evaluate_voltage_limit( ...
        time, [-12.01; -12; -6; 0; 12]);

    assert(within_limits.pass, ...
        'self_check_voltage_limit:ExpectedPass', ...
        'A signal contained within [-12 V, +12 V] did not pass.');
    assert(~upper_violation.pass && ...
        upper_violation.max_upper_exceedance_v > 0, ...
        'self_check_voltage_limit:ExpectedUpperFailure', ...
        'A signal above +12 V did not fail as expected.');
    assert(~lower_violation.pass && ...
        lower_violation.max_lower_exceedance_v > 0, ...
        'self_check_voltage_limit:ExpectedLowerFailure', ...
        'A signal below -12 V did not fail as expected.');

    results = struct( ...
        'within_limits', within_limits, ...
        'upper_violation', upper_violation, ...
        'lower_violation', lower_violation);

    fprintf('Voltage Limit Oracle self-check PASS:\n');
    fprintf('  Within [-12 V, +12 V] -> PASS\n');
    fprintf('  Above +12 V           -> FAIL (expected)\n');
    fprintf('  Below -12 V           -> FAIL (expected)\n');
end
