function results = self_check_tracking()
%SELF_CHECK_TRACKING Exercise the frozen Tracking Oracle boundary semantics.
%
%   This self-check uses a logged-signal-shaped example with a terminal
%   residual of approximately 1e-14 rps, matching the numerical scale seen
%   in healthy AS2308 MIL baseline characterization.

    time = (0:0.001:1).';
    reference = 15 * ones(size(time));
    terminalSamples = time >= time(end) - 0.05;

    healthySpeed = reference;
    healthySpeed(terminalSamples) = reference(terminalSamples) - 1e-14;
    healthy = evaluate_tracking(time, reference, healthySpeed);
    assert(healthy.pass, ...
        'self_check_tracking:HealthyResidualExpectedPass', ...
        'Healthy numerical residual should pass.');

    % Use a zero-valued synthetic reference for an exactly representable
    % subtraction result at the tolerance boundary. This tests the Oracle's
    % <= comparison without floating-point cancellation around 15 rps.
    boundaryReference = zeros(size(time));
    boundarySpeed = boundaryReference;
    boundarySpeed(terminalSamples) = -1e-9;
    boundary = evaluate_tracking( ...
        time, boundaryReference, boundarySpeed);
    assert(boundary.pass, ...
        'self_check_tracking:ToleranceBoundaryExpectedPass', ...
        'An error exactly at the frozen tolerance should pass.');

    aboveToleranceSpeed = boundaryReference;
    aboveToleranceSpeed(terminalSamples) = -2e-9;
    aboveTolerance = evaluate_tracking( ...
        time, boundaryReference, aboveToleranceSpeed);
    assert(~aboveTolerance.pass, ...
        'self_check_tracking:AboveToleranceExpectedFail', ...
        'An error clearly above the frozen tolerance should fail.');

    outsideWindowSpeed = reference;
    outsideWindowSpeed(~terminalSamples) = ...
        reference(~terminalSamples) - 1;
    outsideWindow = evaluate_tracking( ...
        time, reference, outsideWindowSpeed);
    assert(outsideWindow.pass, ...
        'self_check_tracking:OutsideWindowExpectedPass', ...
        'Errors outside the terminal window must not affect the result.');

    results = struct( ...
        'healthy_numerical_residual', healthy, ...
        'exact_tolerance', boundary, ...
        'above_tolerance', aboveTolerance, ...
        'outside_terminal_window', outsideWindow);

    fprintf('Tracking Oracle self-check: 4/4 PASS\n');
    fprintf('  healthy residual %.12g rps -> PASS\n', ...
        healthy.max_abs_error_rps);
    fprintf('  exact tolerance %.12g rps -> PASS\n', ...
        boundary.max_abs_error_rps);
    fprintf('  above tolerance %.12g rps -> FAIL (expected)\n', ...
        aboveTolerance.max_abs_error_rps);
    fprintf('  outside-window error -> PASS\n');
end
