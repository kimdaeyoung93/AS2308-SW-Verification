function results = self_check_direction()
%SELF_CHECK_DIRECTION Exercise ORC-DIR-001 pass and failure cases.

    time = (0:0.001:0.1).';
    positiveReference = 15 * ones(size(time));
    negativeReference = -15 * ones(size(time));
    positiveMotorSpeed = 15 * ones(size(time));
    negativeMotorSpeed = -15 * ones(size(time));

    positiveMatch = evaluate_direction( ...
        time, positiveReference, positiveMotorSpeed);
    negativeMatch = evaluate_direction( ...
        time, negativeReference, negativeMotorSpeed);
    positiveMismatch = evaluate_direction( ...
        time, positiveReference, negativeMotorSpeed);
    negativeMismatch = evaluate_direction( ...
        time, negativeReference, positiveMotorSpeed);

    motorSpeedWithZero = positiveMotorSpeed;
    motorSpeedWithZero(end - 10) = 0;
    zeroMotorSpeed = evaluate_direction( ...
        time, positiveReference, motorSpeedWithZero);

    assert(positiveMatch.pass, ...
        'self_check_direction:ExpectedPositivePass', ...
        'Positive reference with positive motorspeed did not pass.');
    assert(negativeMatch.pass, ...
        'self_check_direction:ExpectedNegativePass', ...
        'Negative reference with negative motorspeed did not pass.');
    assert(~positiveMismatch.pass, ...
        'self_check_direction:ExpectedPositiveMismatchFailure', ...
        'Positive reference with negative motorspeed did not fail.');
    assert(~negativeMismatch.pass, ...
        'self_check_direction:ExpectedNegativeMismatchFailure', ...
        'Negative reference with positive motorspeed did not fail.');
    assert(~zeroMotorSpeed.pass && zeroMotorSpeed.mismatch_sample_count == 1, ...
        'self_check_direction:ExpectedZeroMotorSpeedFailure', ...
        'A zero motorspeed sample in the evaluation window did not fail.');

    results = struct( ...
        'positive_match', positiveMatch, ...
        'negative_match', negativeMatch, ...
        'positive_mismatch', positiveMismatch, ...
        'negative_mismatch', negativeMismatch, ...
        'zero_motorspeed', zeroMotorSpeed);

    fprintf('Direction Oracle self-check PASS:\n');
    fprintf('  +15 reference / positive motorspeed -> PASS\n');
    fprintf('  -15 reference / negative motorspeed -> PASS\n');
    fprintf('  +15 reference / negative motorspeed -> FAIL (expected)\n');
    fprintf('  -15 reference / positive motorspeed -> FAIL (expected)\n');
    fprintf('  zero motorspeed sample in window    -> FAIL (expected)\n');
end
