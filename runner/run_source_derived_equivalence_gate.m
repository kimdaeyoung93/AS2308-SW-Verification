function [gateSummary, stageAMetrics, stageBMetrics, metadata] = ...
        run_source_derived_equivalence_gate()
%RUN_SOURCE_DERIVED_EQUIVALENCE_GATE Run SIL Protocol v1.1 Stage A/B gate.
%
%   This runner performs Normal simulations only. It does not save either
%   model, generate code, build, or execute SIL. All comparisons are exact:
%   no tolerance, interpolation, resampling, or extrapolation is used.

    protocolVersion = "v1.1 Frozen";
    expectedSourceHash = ...
        "4A7FDC070506CA641ACBD2C3EFEA2FEF71DDCC150CA3FC1F20F191B8B998ED4D";
    sourceModelName = 'AS2308_MIL_Baseline_v3';
    derivedModelName = 'AS2308_SIL_B2B_Verification_v1';

    runnerDirectory = fileparts(mfilename('fullpath'));
    repositoryRoot = fileparts(runnerDirectory);
    sourceFile = fullfile( ...
        repositoryRoot, 'model', [sourceModelName, '.slx']);
    derivedFile = fullfile( ...
        repositoryRoot, 'model', 'verification', ...
        [derivedModelName, '.slx']);
    protocolFile = fullfile( ...
        repositoryRoot, 'docs', '04_SIL_BackToBack_Protocol_v1.1.md');
    parameterScript = fullfile( ...
        repositoryRoot, 'model', 'AS2308_calculate_pi_control_cc.m');
    manualRunnerFile = fullfile(runnerDirectory, 'run_manual_mil_suite.m');
    reversalRunnerFile = fullfile( ...
        runnerDirectory, 'run_single_reversal_test.m');
    resultDirectory = fullfile( ...
        repositoryRoot, 'results', 'source_derived_equivalence_v1');

    localAssertFile(sourceFile, 'Frozen source model');
    localAssertFile(derivedFile, 'Derived verification model');
    localAssertFile(protocolFile, 'Frozen SIL Protocol v1.1');
    localAssertFile(parameterScript, 'Controller parameter script');
    localAssertFile(manualRunnerFile, 'Frozen Manual suite runner');
    localAssertFile(reversalRunnerFile, 'Frozen reversal runner');
    localAssertFrozenScenarioDefinitions( ...
        manualRunnerFile, reversalRunnerFile);

    sourceHashBefore = localFileSha256(sourceFile);
    derivedHashBefore = localFileSha256(derivedFile);
    assert(strcmpi(sourceHashBefore, expectedSourceHash), ...
        'run_source_derived_equivalence_gate:SourceHashMismatch', ...
        'Source SHA-256 mismatch. Expected %s, found %s.', ...
        expectedSourceHash, sourceHashBefore);

    run(parameterScript);
    parameters = struct( ...
        'Kps', Kps, 'Kis', Kis, 'Kas', Kas, 'Vdc', Vdc, 'ts', ts);
    localAssertFrozenParameterValues(parameters);

    sourceWasLoaded = bdIsLoaded(sourceModelName);
    derivedWasLoaded = bdIsLoaded(derivedModelName);
    if ~sourceWasLoaded
        load_system(sourceFile);
    end
    if ~derivedWasLoaded
        load_system(derivedFile);
    end
    modelCleanup = onCleanup(@() localRestoreLoadState( ...
        sourceModelName, sourceWasLoaded, ...
        derivedModelName, derivedWasLoaded));

    assert(strcmp(get_param(sourceModelName, 'Dirty'), 'off'), ...
        'run_source_derived_equivalence_gate:DirtySourceModel', ...
        'Frozen source model must be clean before execution.');
    assert(strcmp(get_param(derivedModelName, 'Dirty'), 'off'), ...
        'run_source_derived_equivalence_gate:DirtyDerivedModel', ...
        'Derived model must be clean before execution.');
    localAssertStoredConfiguration(sourceModelName, parameters.ts);
    localAssertStoredConfiguration(derivedModelName, parameters.ts);
    localAssertSignalSemantics(sourceModelName, derivedModelName);

    scenarios = localFrozenScenarios(parameters.ts);
    sourcePaths = localSourcePaths(sourceModelName);
    localEnsureDirectory(resultDirectory);

    summaryRows = repmat(localEmptySummaryRow(), numel(scenarios), 1);
    stageARows = repmat(localEmptyMetricRow(), 0, 1);
    stageBRows = repmat(localEmptyMetricRow(), 0, 1);

    fprintf('\nSource-to-Derived Equivalence Gate — Protocol %s\n', ...
        protocolVersion);
    fprintf('Comparison: exact major-grid equality; tolerance: NONE\n');
    fprintf('Simulation mode: Normal only\n\n');

    for scenarioIndex = 1:numel(scenarios)
        scenario = scenarios(scenarioIndex);
        row = localEmptySummaryRow();
        row.ScenarioID = scenario.id;
        row.FrozenTestCase = scenario.frozen_test_case;
        row.InputDefinition = scenario.input_description;
        row.StageA_Status = "EXECUTION_ERROR";
        row.StageB_Status = "NOT_RUN";
        row.Overall_Status = "EXECUTION_ERROR";

        fprintf('%s — %s\n', scenario.id, scenario.input_description);
        try
            sourceInput = localSourceSimulationInput( ...
                sourceModelName, sourcePaths, scenario, parameters);
            derivedInput = localDerivedSimulationInput( ...
                derivedModelName, scenario, parameters);

            sourceOutput = sim(sourceInput);
            derivedOutput = sim(derivedInput);

            sourceSignals = localInternalSignals(sourceOutput);
            derivedSignals = localInternalSignals(derivedOutput);
            localAssertSourceWaveform(sourceOutput, scenario);

            [stageAStatus, newRows] = localCompareSignalSet( ...
                scenario.id, "Stage A", ...
                sourceSignals, derivedSignals);
            stageARows = [stageARows; newRows]; %#ok<AGROW>
            row.StageA_Status = stageAStatus;

            if stageAStatus ~= "PASS"
                if stageAStatus == "DERIVATION_MISMATCH"
                    row.Overall_Status = "DERIVATION_MISMATCH";
                else
                    row.Overall_Status = "EXECUTION_ERROR";
                end
                row.Notes = "Stage B not run because Stage A did not pass.";
            else
                sampledSignals = localSampledRootOutputs(derivedOutput);
                [stageBStatus, newRows] = localCompareSignalSet( ...
                    scenario.id, "Stage B", ...
                    derivedSignals, sampledSignals);
                stageBRows = [stageBRows; newRows]; %#ok<AGROW>
                row.StageB_Status = stageBStatus;
                if stageBStatus == "PASS"
                    row.Overall_Status = "PASS";
                elseif stageBStatus == "DERIVATION_MISMATCH"
                    row.Overall_Status = "DERIVATION_MISMATCH";
                else
                    row.Overall_Status = "EXECUTION_ERROR";
                end
            end
        catch exception
            if row.StageA_Status == "PASS"
                row.StageB_Status = "EXECUTION_ERROR";
            else
                row.StageA_Status = "EXECUTION_ERROR";
                row.StageB_Status = "NOT_RUN";
            end
            row.Overall_Status = "EXECUTION_ERROR";
            row.Notes = string(exception.identifier) + ": " + ...
                string(exception.message);
            fprintf('  EXECUTION_ERROR: %s\n', exception.message);
        end
        summaryRows(scenarioIndex) = row;
        fprintf('  Stage A: %s | Stage B: %s | Overall: %s\n\n', ...
            row.StageA_Status, row.StageB_Status, row.Overall_Status);
    end

    gateSummary = struct2table(summaryRows);
    stageAMetrics = localMetricTable(stageARows);
    stageBMetrics = localMetricTable(stageBRows);

    sourceHashAfter = localFileSha256(sourceFile);
    derivedHashAfter = localFileSha256(derivedFile);
    assert(strcmpi(sourceHashAfter, sourceHashBefore), ...
        'run_source_derived_equivalence_gate:SourceHashChanged', ...
        'Source model SHA-256 changed during gate execution.');
    assert(strcmpi(sourceHashAfter, expectedSourceHash), ...
        'run_source_derived_equivalence_gate:FinalSourceHashMismatch', ...
        'Source model no longer matches the frozen hash.');
    assert(strcmpi(derivedHashAfter, derivedHashBefore), ...
        'run_source_derived_equivalence_gate:DerivedHashChanged', ...
        'Derived model SHA-256 changed during gate execution.');
    assert(strcmp(get_param(sourceModelName, 'Dirty'), 'off'), ...
        'run_source_derived_equivalence_gate:SourceBecameDirty', ...
        'Source model became dirty during gate execution.');
    assert(strcmp(get_param(derivedModelName, 'Dirty'), 'off'), ...
        'run_source_derived_equivalence_gate:DerivedBecameDirty', ...
        'Derived model became dirty during gate execution.');

    metadata = struct( ...
        'ProtocolVersion', protocolVersion, ...
        'SourceSHA256Before', sourceHashBefore, ...
        'SourceSHA256After', sourceHashAfter, ...
        'DerivedSHA256Before', derivedHashBefore, ...
        'DerivedSHA256After', derivedHashAfter, ...
        'MATLABRelease', string(version('-release')), ...
        'Solver', string(get_param(sourceModelName, 'Solver')), ...
        'FixedStep', string(get_param(sourceModelName, 'FixedStep')), ...
        'Kps', parameters.Kps, ...
        'Kis', parameters.Kis, ...
        'Kas', parameters.Kas, ...
        'Vdc', parameters.Vdc, ...
        'ts', parameters.ts, ...
        'OverallGatePass', all(gateSummary.Overall_Status == "PASS"));

    writetable(gateSummary, fullfile(resultDirectory, 'gate_summary.csv'));
    writetable(stageAMetrics, fullfile(resultDirectory, 'stage_a_metrics.csv'));
    writetable(stageBMetrics, fullfile(resultDirectory, 'stage_b_metrics.csv'));
    localWriteMetadata( ...
        fullfile(resultDirectory, 'metadata.txt'), metadata, scenarios);

    fprintf('Gate summary:\n');
    disp(gateSummary(:, { ...
        'ScenarioID', 'StageA_Status', 'StageB_Status', 'Overall_Status'}));
    fprintf('Source SHA before/after: %s / %s\n', ...
        sourceHashBefore, sourceHashAfter);
    fprintf('Derived SHA before/after: %s / %s\n', ...
        derivedHashBefore, derivedHashAfter);
    fprintf('Overall gate: %s\n\n', ...
        localPassFail(metadata.OverallGatePass));

    clear modelCleanup;
end

function simulationInput = localSourceSimulationInput( ...
        modelName, paths, scenario, parameters)
    simulationInput = Simulink.SimulationInput(modelName);
    simulationInput = localSetVariables(simulationInput, parameters);
    simulationInput = simulationInput.setVariable('SpeedRef_cmd', 0);

    if scenario.kind == "constant"
        simulationInput = simulationInput.setVariable( ...
            'SpeedRef_cmd', scenario.values_rps(1));
    else
        initialDirection = sign(scenario.values_rps(1));
        pulsePeriod_s = 2 * scenario.stop_time_s;
        pulseWidth_pct = ...
            100 * scenario.switch_time_s / pulsePeriod_s;
        simulationInput = simulationInput.setBlockParameter( ...
            paths.pulseGenerator, 'Amplitude', ...
            sprintf('%g', 2 * initialDirection));
        simulationInput = simulationInput.setBlockParameter( ...
            paths.pulseGenerator, 'Period', ...
            sprintf('%.17g', pulsePeriod_s));
        simulationInput = simulationInput.setBlockParameter( ...
            paths.pulseGenerator, 'PulseWidth', ...
            sprintf('%.17g', pulseWidth_pct));
        simulationInput = simulationInput.setBlockParameter( ...
            paths.pulseGenerator, 'PhaseDelay', '0');
        simulationInput = simulationInput.setBlockParameter( ...
            paths.referenceOffset, ...
            'Value', sprintf('%g', initialDirection));
        simulationInput = simulationInput.setBlockParameter( ...
            paths.referenceSwitch, 'CurrentSetting', '1');
    end
    simulationInput = localNormalLoggingConfiguration( ...
        simulationInput, scenario.stop_time_s, false);
end

function simulationInput = localDerivedSimulationInput( ...
        modelName, scenario, parameters)
    simulationInput = Simulink.SimulationInput(modelName);
    simulationInput = localSetVariables(simulationInput, parameters);
    inputDataset = Simulink.SimulationData.Dataset;
    inputSeries = timeseries( ...
        scenario.input_values_rps, scenario.input_time_s);
    inputSeries.Name = 'SpeedRef_rps';
    inputDataset = inputDataset.addElement( ...
        inputSeries, 'SpeedRef_rps');
    simulationInput = simulationInput.setExternalInput(inputDataset);
    simulationInput = localNormalLoggingConfiguration( ...
        simulationInput, scenario.stop_time_s, true);
end

function simulationInput = localSetVariables(simulationInput, parameters)
    names = fieldnames(parameters);
    for index = 1:numel(names)
        simulationInput = simulationInput.setVariable( ...
            names{index}, parameters.(names{index}));
    end
end

function simulationInput = localNormalLoggingConfiguration( ...
        simulationInput, stopTime_s, saveRootOutput)
    simulationInput = simulationInput.setModelParameter( ...
        'SimulationMode', 'normal', ...
        'StopTime', sprintf('%.17g', stopTime_s), ...
        'SignalLogging', 'on', ...
        'SignalLoggingName', 'logsout', ...
        'SignalLoggingSaveFormat', 'Dataset', ...
        'ReturnWorkspaceOutputs', 'on');
    if saveRootOutput
        simulationInput = simulationInput.setModelParameter( ...
            'SaveOutput', 'on', ...
            'OutputSaveName', 'yout', ...
            'SaveFormat', 'Dataset');
    end
end

function signals = localInternalSignals(simulationOutput)
    logsout = simulationOutput.get('logsout');
    signals = struct( ...
        'Vcmd', localSignal(localGetDatasetElement(logsout, 'Vcmd')), ...
        'MotorSpeed', localSignal( ...
            localGetDatasetElement(logsout, 'motorspeed')));
end

function signals = localSampledRootOutputs(simulationOutput)
    yout = simulationOutput.get('yout');
    assert(isa(yout, 'Simulink.SimulationData.Dataset'), ...
        'run_source_derived_equivalence_gate:InvalidRootOutput', ...
        'Derived root output yout is not a Dataset.');
    assert(yout.numElements == 2, ...
        'run_source_derived_equivalence_gate:RootOutputCountMismatch', ...
        'Expected two derived root outputs, found %d.', yout.numElements);
    % Frozen structural audit establishes Outport 1 = sampled_Vcmd and
    % Outport 2 = sampled_MotorSpeed. R2023b does not necessarily use the
    % root Outport block name as the Dataset element Name.
    signals = struct( ...
        'Vcmd', localSignal(yout.getElement(1)), ...
        'MotorSpeed', localSignal(yout.getElement(2)));
end

function signal = localGetDatasetElement(dataset, elementName)
    assert(isa(dataset, 'Simulink.SimulationData.Dataset'), ...
        'run_source_derived_equivalence_gate:InvalidDataset', ...
        'Expected Dataset while retrieving signal %s.', elementName);
    signal = dataset.getElement(char(elementName));
end

function result = localSignal(signal)
    values = signal.Values;
    result = struct( ...
        'time', double(values.Time(:)), ...
        'data', double(squeeze(values.Data)));
    result.data = result.data(:);
    assert(numel(result.time) == numel(result.data), ...
        'run_source_derived_equivalence_gate:SignalLengthMismatch', ...
        'Signal time/data lengths differ.');
    assert(all(isfinite(result.time)) && all(isfinite(result.data)), ...
        'run_source_derived_equivalence_gate:NonFiniteSignal', ...
        'Signal contains NaN or Inf.');
end

function [status, rows] = localCompareSignalSet( ...
        scenarioID, stageName, leftSignals, rightSignals)
    signalNames = ["Vcmd", "MotorSpeed"];
    rows = repmat(localEmptyMetricRow(), numel(signalNames), 1);
    status = "PASS";
    for index = 1:numel(signalNames)
        name = signalNames(index);
        left = leftSignals.(name);
        right = rightSignals.(name);
        row = localEmptyMetricRow();
        row.ScenarioID = scenarioID;
        row.Stage = stageName;
        row.Signal = name;
        row.SampleCountLeft = numel(left.data);
        row.SampleCountRight = numel(right.data);
        row.SampleCountExact = ...
            row.SampleCountLeft == row.SampleCountRight;
        row.TimeVectorExact = row.SampleCountExact && ...
            isequal(left.time, right.time);
        if ~row.SampleCountExact || ~row.TimeVectorExact
            row.Status = "EXECUTION_ERROR";
            row.Notes = "Time-grid construction/alignment mismatch.";
            status = "EXECUTION_ERROR";
            rows(index) = row;
            continue;
        end

        difference = left.data - right.data;
        differing = left.data ~= right.data;
        row.MaxAbsDiff = max(abs(difference));
        row.RmsDiff = sqrt(mean(difference .^ 2));
        row.DifferingSampleCount = sum(differing);
        firstIndex = find(differing, 1, 'first');
        if isempty(firstIndex)
            row.FirstDifferingIndex = NaN;
            row.FirstDifferingTime_s = NaN;
            row.Status = "PASS";
        else
            row.FirstDifferingIndex = firstIndex;
            row.FirstDifferingTime_s = left.time(firstIndex);
            row.Status = "DERIVATION_MISMATCH";
            if status ~= "EXECUTION_ERROR"
                status = "DERIVATION_MISMATCH";
            end
        end
        rows(index) = row;
    end
end

function localAssertSourceWaveform(simulationOutput, scenario)
    logsout = simulationOutput.get('logsout');
    reference = localSignal(localGetDatasetElement(logsout, 'reference'));
    expected = localWaveformAtTimes(reference.time, scenario);
    assert(isequal(reference.data, expected), ...
        'run_source_derived_equivalence_gate:FrozenWaveformMismatch', ...
        'Source logged reference does not match frozen waveform: %s', ...
        scenario.id);
    if scenario.kind == "reversal"
        transitionIndex = find( ...
            reference.time == scenario.switch_time_s, 1, 'first');
        assert(~isempty(transitionIndex), ...
            'run_source_derived_equivalence_gate:MissingTransitionSample', ...
            'Source reference has no sample at t = %.17g s.', ...
            scenario.switch_time_s);
        assert(reference.data(transitionIndex) == scenario.values_rps(2), ...
            'run_source_derived_equivalence_gate:TransitionValueMismatch', ...
            'Frozen source value at t = %.17g s is not %.17g rps.', ...
            scenario.switch_time_s, scenario.values_rps(2));
    end
end

function values = localWaveformAtTimes(time, scenario)
    values = repmat(scenario.values_rps(1), size(time));
    if scenario.kind == "reversal"
        values(time >= scenario.switch_time_s) = scenario.values_rps(2);
    end
end

function scenarios = localFrozenScenarios(sampleTime)
    scenarios = repmat(struct( ...
        'id', "", 'frozen_test_case', "", 'kind', "", ...
        'values_rps', [], 'stop_time_s', NaN, 'switch_time_s', NaN, ...
        'input_description', "", 'input_time_s', [], ...
        'input_values_rps', []), 3, 1);

    scenarios(1) = localScenario( ...
        "GATE-001", "MTC-002 / IT-001", "constant", 2, 1, NaN, ...
        "+2 rps, 0-1 s", sampleTime);
    scenarios(2) = localScenario( ...
        "GATE-002", "MTC-001 / IT-001", "constant", 16.75, 1, NaN, ...
        "+16.75 rps, 0-1 s", sampleTime);
    scenarios(3) = localScenario( ...
        "GATE-003", "MTC-004 / IT-001", "reversal", [15 -15], 4, 2, ...
        "+15 rps [0,2 s), -15 rps [2,4 s]", sampleTime);
end

function scenario = localScenario( ...
        id, frozenTestCase, kind, values, stopTime, switchTime, ...
        description, sampleTime)
    sampleCount = round(stopTime / sampleTime);
    time = (0:sampleCount)' * sampleTime;
    assert(time(end) == stopTime, ...
        'Frozen stop time is not represented exactly on the major grid.');
    scenario = struct( ...
        'id', id, ...
        'frozen_test_case', frozenTestCase, ...
        'kind', kind, ...
        'values_rps', values, ...
        'stop_time_s', stopTime, ...
        'switch_time_s', switchTime, ...
        'input_description', description, ...
        'input_time_s', time, ...
        'input_values_rps', []);
    scenario.input_values_rps = localWaveformAtTimes(time, scenario);
    if kind == "reversal"
        transitionIndex = round(switchTime / sampleTime) + 1;
        assert(time(transitionIndex) == switchTime, ...
            'Reversal transition is not on the major grid.');
        assert(scenario.input_values_rps(transitionIndex - 1) == values(1));
        assert(scenario.input_values_rps(transitionIndex) == values(2));
    end
end

function paths = localSourcePaths(modelName)
    pulseBlocks = find_system(modelName, ...
        'LookUnderMasks', 'all', 'FollowLinks', 'on', ...
        'BlockType', 'DiscretePulseGenerator');
    assert(numel(pulseBlocks) == 1, ...
        'Expected exactly one source DiscretePulseGenerator.');
    paths = struct( ...
        'pulseGenerator', pulseBlocks{1}, ...
        'referenceOffset', [modelName, '/Constant2'], ...
        'referenceSwitch', [modelName, '/Manual Switch']);
end

function localAssertSignalSemantics(sourceModelName, derivedModelName)
    assert(strcmp(get_param([sourceModelName, '/Gain4'], 'Gain'), ...
        '1/(2*pi)'), 'Source MotorSpeed comparison point is not rps.');
    assert(strcmp(get_param([derivedModelName, '/Gain4'], 'Gain'), ...
        '1/(2*pi)'), 'Derived MotorSpeed comparison point is not rps.');
    assert(strcmp(get_param( ...
        [sourceModelName, '/PI Speed Controller/Saturation'], ...
        'BlockType'), 'Saturate'));
    assert(strcmp(get_param( ...
        [derivedModelName, '/PI Speed Controller/Saturation'], ...
        'BlockType'), 'Saturate'));
end

function localAssertStoredConfiguration(modelName, sampleTime)
    assert(strcmp(get_param(modelName, 'SolverType'), 'Fixed-step'));
    assert(strcmp(get_param(modelName, 'Solver'), 'ode4'));
    assert(strcmp(get_param(modelName, 'FixedStep'), 'ts'));
    assert(sampleTime == 0.0004);
end

function localAssertFrozenParameterValues(parameters)
    expectedKps = (2 * pi * 40) / 2185.96;
    expectedKis = 17.76 * expectedKps;
    expectedKas = expectedKis / expectedKps;
    assert(parameters.ts == 0.0004);
    assert(parameters.Vdc == 12);
    assert(parameters.Kps == expectedKps);
    assert(parameters.Kis == expectedKis);
    assert(parameters.Kas == expectedKas);
end

function localAssertFrozenScenarioDefinitions( ...
        manualRunnerFile, reversalRunnerFile)
    manualSource = string(regexprep(fileread(manualRunnerFile), '\s+', ' '));
    reversalSource = string(regexprep( ...
        fileread(reversalRunnerFile), '\s+', ' '));
    manualAnchors = [ ...
        "constantReferences = [16.75; -16.75; 2; -2; 15; -15];"; ...
        "constantReferences(runIndex), 1);"; ...
        "'SpeedRef_cmd', reference_rps);" ];
    reversalAnchors = [ ...
        "addParameter(parser, 'SwitchingTime_s', 2, @localPositiveScalar);"; ...
        "addParameter(parser, 'StopTime_s', 4, @localPositiveScalar);"; ...
        "initial_reference_rps = [15; -15];"; ...
        "reversed_reference_rps = -initial_reference_rps;"; ...
        "pulsePeriod_s = 2 * stopTime_s;"; ...
        "pulseWidth_pct = 100 * switchingTime_s / pulsePeriod_s;"; ...
        "'Amplitude', sprintf('%g', 2 * initialDirection));"; ...
        "referenceSwitch, 'CurrentSetting', '1');" ];
    localAssertAnchors(manualSource, manualAnchors, manualRunnerFile);
    localAssertAnchors(reversalSource, reversalAnchors, reversalRunnerFile);
end

function localAssertAnchors(source, anchors, filePath)
    for index = 1:numel(anchors)
        assert(contains(source, anchors(index)), ...
            'Frozen scenario definition changed in %s. Missing: %s', ...
            filePath, anchors(index));
    end
end

function tableValue = localMetricTable(rows)
    if isempty(rows)
        tableValue = struct2table(localEmptyMetricRow());
        tableValue(1, :) = [];
    else
        tableValue = struct2table(rows);
    end
end

