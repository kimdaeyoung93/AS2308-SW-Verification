end

function localWriteMetadata(filePath, metadata, scenarios)
    fileIdentifier = fopen(filePath, 'wt');
    if fileIdentifier < 0
        error('Could not open metadata file: %s', filePath);
    end
    closeFile = onCleanup(@() fclose(fileIdentifier));
    fprintf(fileIdentifier, 'Protocol: %s\n', metadata.ProtocolVersion);
    fprintf(fileIdentifier, 'Source SHA before: %s\n', ...
        metadata.SourceSHA256Before);
    fprintf(fileIdentifier, 'Source SHA after: %s\n', ...
        metadata.SourceSHA256After);
    fprintf(fileIdentifier, 'Derived SHA before: %s\n', ...
        metadata.DerivedSHA256Before);
    fprintf(fileIdentifier, 'Derived SHA after: %s\n', ...
        metadata.DerivedSHA256After);
    fprintf(fileIdentifier, 'MATLAB release: %s\n', metadata.MATLABRelease);
    fprintf(fileIdentifier, 'Solver: %s\n', metadata.Solver);
    fprintf(fileIdentifier, 'FixedStep: %s (ts = %.17g s)\n', ...
        metadata.FixedStep, metadata.ts);
    fprintf(fileIdentifier, 'Kps: %.17g\n', metadata.Kps);
    fprintf(fileIdentifier, 'Kis: %.17g\n', metadata.Kis);
    fprintf(fileIdentifier, 'Kas: %.17g\n', metadata.Kas);
    fprintf(fileIdentifier, 'Vdc: %.17g\n', metadata.Vdc);
    fprintf(fileIdentifier, 'ts: %.17g\n', metadata.ts);
    fprintf(fileIdentifier, ['Vcmd internal comparison path: ', ...
        'PI Speed Controller Saturation output (logged Vcmd)\n']);
    fprintf(fileIdentifier, ['MotorSpeed internal comparison path: ', ...
        'Transfer Fcn2 output through Gain4 = 1/(2*pi), ', ...
        'logged motorspeed [rps]\n']);
    fprintf(fileIdentifier, ['Stage B sampled outputs: ', ...
        'sampled_Vcmd, sampled_MotorSpeed\n']);
    for index = 1:numel(scenarios)
        fprintf(fileIdentifier, 'Scenario %s: %s; %s\n', ...
            scenarios(index).id, scenarios(index).frozen_test_case, ...
            scenarios(index).input_description);
    end
    fprintf(fileIdentifier, 'Execution timestamp: %s\n', ...
        char(datetime('now', 'TimeZone', 'local', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ssXXX')));
    clear closeFile;
end

function localRestoreLoadState( ...
        sourceModelName, sourceWasLoaded, derivedModelName, derivedWasLoaded)
    localRestoreOneModel(sourceModelName, sourceWasLoaded);
    localRestoreOneModel(derivedModelName, derivedWasLoaded);
end

function localRestoreOneModel(modelName, wasLoaded)
    if ~bdIsLoaded(modelName)
        return;
    end
    if ~strcmp(get_param(modelName, 'Dirty'), 'off')
        warning('run_source_derived_equivalence_gate:DirtyModelLeftOpen', ...
            'Model became dirty and was left open without saving: %s', ...
            modelName);
        return;
    end
    if ~wasLoaded
        close_system(modelName, 0);
    end
end

function localAssertFile(filePath, description)
    assert(isfile(filePath), '%s not found: %s', description, filePath);
end

function localEnsureDirectory(directoryPath)
    if ~isfolder(directoryPath)
        [created, message] = mkdir(directoryPath);
        assert(created, 'Could not create directory %s: %s', ...
            directoryPath, message);
    end
end

function hashValue = localFileSha256(filePath)
    fileIdentifier = fopen(filePath, 'rb');
    if fileIdentifier < 0
        error('Could not open file for hashing: %s', filePath);
    end
    closeFile = onCleanup(@() fclose(fileIdentifier));
    bytes = fread(fileIdentifier, Inf, '*uint8');
    clear closeFile;
    digest = java.security.MessageDigest.getInstance('SHA-256');
    digest.update(typecast(bytes(:), 'int8'));
    digestBytes = typecast(digest.digest(), 'uint8');
    hashValue = upper(string(reshape(dec2hex(digestBytes, 2).', 1, [])));
end

function text = localPassFail(pass)
    if pass
        text = 'PASS';
    else
        text = 'FAIL';
    end
end
