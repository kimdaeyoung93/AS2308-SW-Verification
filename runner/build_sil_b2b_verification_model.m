function result = build_sil_b2b_verification_model()
%BUILD_SIL_B2B_VERIFICATION_MODEL Create the frozen SIL v1.1 derived model.
%
%   RESULT = BUILD_SIL_B2B_VERIFICATION_MODEL() verifies the frozen source
%   model hash, creates a derived top-model SIL verification model, adds a
%   discrete root input and observation-only Zero-Order Hold outputs, and
%   performs structural checks. The function does not simulate, compile,
%   generate code, or modify/save the frozen source model.

    protocolVersion = "v1.1 Frozen";
    expectedSourceHash = ...
        "4A7FDC070506CA641ACBD2C3EFEA2FEF71DDCC150CA3FC1F20F191B8B998ED4D";
    sourceModelName = 'AS2308_MIL_Baseline_v3';
    derivedModelName = 'AS2308_SIL_B2B_Verification_v1';

    runnerDirectory = fileparts(mfilename('fullpath'));
    repositoryRoot = fileparts(runnerDirectory);
    sourceFile = fullfile( ...
        repositoryRoot, 'model', [sourceModelName, '.slx']);
    parameterScript = fullfile( ...
        repositoryRoot, 'model', 'AS2308_calculate_pi_control_cc.m');
    protocolFile = fullfile( ...
        repositoryRoot, 'docs', '04_SIL_BackToBack_Protocol_v1.1.md');
    verificationDirectory = fullfile(repositoryRoot, 'model', 'verification');
    derivedFile = fullfile( ...
        verificationDirectory, [derivedModelName, '.slx']);
    manifestFile = fullfile( ...
        verificationDirectory, ...
        [derivedModelName, '_manifest.txt']);

    localAssertFile(sourceFile, 'Frozen source model');
    localAssertFile(parameterScript, 'Controller parameter script');
    localAssertFile(protocolFile, 'Frozen SIL Protocol v1.1');

    sourceHashBefore = localFileSha256(sourceFile);
    assert(strcmpi(sourceHashBefore, expectedSourceHash), ...
        'build_sil_b2b_verification_model:SourceHashMismatch', ...
        'Source SHA-256 mismatch. Expected %s, found %s.', ...
        expectedSourceHash, sourceHashBefore);

    % The frozen parameter script is evaluated in this function workspace.
    % It is not used to modify the base workspace or the source model.
    run(parameterScript);
    parameters = struct( ...
        'Kps', Kps, 'Kis', Kis, 'Kas', Kas, 'Vdc', Vdc, 'ts', ts);
    localAssertFrozenParameterValues(parameters);

    sourceWasLoaded = bdIsLoaded(sourceModelName);
    if ~sourceWasLoaded
        load_system(sourceFile);
    end
    sourceCleanup = onCleanup( ...
        @() localCloseCleanModelOpenedHere(sourceModelName, sourceWasLoaded));

    assert(strcmp(get_param(sourceModelName, 'Dirty'), 'off'), ...
        'build_sil_b2b_verification_model:DirtySourceModel', ...
        'Frozen source model must be clean before derivation.');
    localAssertSourceConfiguration(sourceModelName, parameters.ts);
    sourceSignatures = localCaptureFrozenSignatures(sourceModelName);

    localEnsureDirectory(verificationDirectory);
    localRecoverIncompleteDerivedArtifact( ...
        derivedModelName, derivedFile, manifestFile, sourceHashBefore);
    assert(~bdIsLoaded(derivedModelName), ...
        'build_sil_b2b_verification_model:DerivedModelLoaded', ...
        'Derived model is already loaded: %s', derivedModelName);
    assert(~isfile(derivedFile), ...
        'build_sil_b2b_verification_model:DerivedModelExists', ...
        ['Refusing to overwrite existing derived model. Remove or archive ', ...
         'the existing artifact before intentional regeneration: %s'], ...
        derivedFile);
    assert(~isfile(manifestFile), ...
        'build_sil_b2b_verification_model:ManifestExists', ...
        ['Refusing to overwrite existing manifest. Remove or archive ', ...
         'the existing artifact before intentional regeneration: %s'], ...
        manifestFile);

    [copied, copyMessage] = copyfile(sourceFile, derivedFile);
    assert(copied, ...
        'build_sil_b2b_verification_model:SourceCopyFailed', ...
        'Could not create derived model copy: %s', copyMessage);

    load_system(derivedFile);
    derivedCleanup = onCleanup( ...
        @() localCloseDerivedModel( ...
        derivedModelName, derivedFile, manifestFile, sourceHashBefore));

    localApplyAllowedTransformations(derivedModelName);
    save_system(derivedModelName, derivedFile);

    structuralChecks = localStructuralSelfCheck( ...
        sourceModelName, derivedModelName, parameters, sourceSignatures);
    assert(strcmp(get_param(derivedModelName, 'Dirty'), 'off'), ...
        'build_sil_b2b_verification_model:DerivedModelNotSaved', ...
        'Derived model remained dirty after save_system.');
    assert(isfile(derivedFile), ...
        'build_sil_b2b_verification_model:DerivedModelMissing', ...
        'Derived model was not saved successfully: %s', derivedFile);

    sourceHashAfter = localFileSha256(sourceFile);
    structuralChecks.source_sha_unchanged = strcmpi( ...
        sourceHashAfter, sourceHashBefore) && ...
        strcmpi(sourceHashAfter, expectedSourceHash);
    structuralChecks.derived_model_saved = ...
        isfile(derivedFile) && strcmp( ...
        get_param(derivedModelName, 'Dirty'), 'off');
    assert(all(struct2array(structuralChecks)), ...
        'build_sil_b2b_verification_model:StructuralSelfCheckFailed', ...
        'One or more derived-model structural checks failed.');
    assert(strcmpi(sourceHashAfter, sourceHashBefore), ...
        'build_sil_b2b_verification_model:SourceModified', ...
        'Frozen source SHA-256 changed during derivation.');
    assert(strcmpi(sourceHashAfter, expectedSourceHash), ...
        'build_sil_b2b_verification_model:FinalSourceHashMismatch', ...
        'Frozen source SHA-256 no longer matches the protocol baseline.');
    assert(strcmp(get_param(sourceModelName, 'Dirty'), 'off'), ...
        'build_sil_b2b_verification_model:SourceBecameDirty', ...
        'Frozen source model became dirty during derivation.');

    localWriteManifest( ...
        manifestFile, protocolVersion, sourceFile, sourceHashAfter, ...
        derivedFile, derivedModelName, parameters);
    assert(isfile(manifestFile), ...
        'build_sil_b2b_verification_model:ManifestMissing', ...
        'Derivation manifest was not written successfully: %s', manifestFile);

    result = struct( ...
        'protocol_version', protocolVersion, ...
        'source_sha256_expected', expectedSourceHash, ...
        'source_sha256_before', sourceHashBefore, ...
        'source_sha256_after', sourceHashAfter, ...
        'source_sha_check_pass', true, ...
        'derived_model_path', string(derivedFile), ...
        'manifest_path', string(manifestFile), ...
        'solver', string(get_param(derivedModelName, 'Solver')), ...
        'fixed_step', string(get_param(derivedModelName, 'FixedStep')), ...
        'root_inputs', "SpeedRef_rps", ...
        'root_outputs', ["sampled_Vcmd", "sampled_MotorSpeed"], ...
        'observation_sample_times', [string(ts), string(ts)], ...
        'controller_integrator_type', "Integrator", ...
        'source_model_modified', false, ...
        'structural_self_check_pass', true, ...
        'structural_checks', structuralChecks);

    fprintf('\nSIL B2B derived verification model generation\n');
    fprintf('Source SHA-256: %s (PASS)\n', sourceHashAfter);
    fprintf('Derived model: %s\n', derivedFile);
    fprintf('Manifest: %s\n', manifestFile);
    fprintf('Solver / FixedStep: %s / %s (ts = %.17g s)\n', ...
        get_param(derivedModelName, 'Solver'), ...
        get_param(derivedModelName, 'FixedStep'), parameters.ts);
    fprintf('Root input: SpeedRef_rps\n');
    fprintf('Root outputs: sampled_Vcmd, sampled_MotorSpeed\n');
    fprintf('ZOH SampleTime: ts = %.17g s, ts = %.17g s\n', ...
        parameters.ts, parameters.ts);
    fprintf('Controller integrator: Integrator (continuous)\n');
    fprintf('Source model modified: false\n');
    fprintf('Structural self-check: PASS\n\n');

    clear derivedCleanup sourceCleanup;
end

function localApplyAllowedTransformations(modelName)
    paths = localPaths(modelName);

    % Remove the complete model-internal test-stimulus network. Gain2 is
    % intentionally retained because it is the frozen rps-to-rad/s (2*pi)
    % conversion immediately before the controller reference input.
    stimulusBlocks = { ...
        paths.constantOffset, ...
        paths.pulseGenerator, ...
        paths.referenceSubtract, ...
        paths.referenceMagnitudeGain, ...
        paths.referenceSwitch, ...
        paths.sineWave, ...
        paths.zeroConstant, ...
        paths.waveformSwitch};
    for index = 1:numel(stimulusBlocks)
        localAssertBlock(stimulusBlocks{index});
    end
    for index = 1:numel(stimulusBlocks)
        delete_block(stimulusBlocks{index});
    end

    inputPath = [modelName, '/SpeedRef_rps'];
    add_block('simulink/Sources/In1', inputPath, ...
        'Port', '1', ...
        'SampleTime', 'ts', ...
        'Position', [300 300 330 320]);
    localDisconnectInput([modelName, '/Gain2'], 1);
    localConnectPorts(inputPath, 1, [modelName, '/Gain2'], 1);

    vcmdZohPath = [modelName, '/Observe_Vcmd_ZOH'];
    speedZohPath = [modelName, '/Observe_MotorSpeed_ZOH'];
    vcmdOutPath = [modelName, '/sampled_Vcmd'];
    speedOutPath = [modelName, '/sampled_MotorSpeed'];

    add_block('simulink/Discrete/Zero-Order Hold', vcmdZohPath, ...
        'SampleTime', 'ts', ...
        'Position', [1110 410 1180 440]);
    add_block('simulink/Sinks/Out1', vcmdOutPath, ...
        'Port', '1', ...
        'Position', [1230 415 1260 435]);
    localConnectPorts( ...
        [modelName, '/PI Speed Controller'], 1, vcmdZohPath, 1);
    localConnectPorts(vcmdZohPath, 1, vcmdOutPath, 1);

    add_block('simulink/Discrete/Zero-Order Hold', speedZohPath, ...
        'SampleTime', 'ts', ...
        'Position', [1620 390 1690 420]);
    add_block('simulink/Sinks/Out1', speedOutPath, ...
        'Port', '2', ...
        'Position', [1740 395 1770 415]);
    localConnectPorts([modelName, '/Gain4'], 1, speedZohPath, 1);
    localConnectPorts(speedZohPath, 1, speedOutPath, 1);
end

function localDisconnectInput(blockPath, portNumber)
    ports = get_param(blockPath, 'PortHandles');
    assert(numel(ports.Inport) >= portNumber, ...
        'Input port %d does not exist: %s', portNumber, blockPath);
    lineHandle = get_param(ports.Inport(portNumber), 'Line');
    if lineHandle ~= -1
        delete_line(lineHandle);
    end
end

function localConnectPorts( ...
        sourceBlock, sourcePortNumber, destinationBlock, destinationPortNumber)
    sourcePorts = get_param(sourceBlock, 'PortHandles');
    destinationPorts = get_param(destinationBlock, 'PortHandles');
    assert(numel(sourcePorts.Outport) >= sourcePortNumber, ...
        'Output port %d does not exist: %s', ...
        sourcePortNumber, sourceBlock);
    assert(numel(destinationPorts.Inport) >= destinationPortNumber, ...
        'Input port %d does not exist: %s', ...
        destinationPortNumber, destinationBlock);
    assert(get_param( ...
        destinationPorts.Inport(destinationPortNumber), 'Line') == -1, ...
        'Destination port is already connected: %s/%d', ...
        destinationBlock, destinationPortNumber);
    modelName = bdroot(sourceBlock);
    add_line(modelName, ...
        sourcePorts.Outport(sourcePortNumber), ...
        destinationPorts.Inport(destinationPortNumber), ...
        'autorouting', 'on');
end

function checks = localStructuralSelfCheck( ...
        sourceModelName, derivedModelName, parameters, sourceSignatures)
    controllerPath = [derivedModelName, '/PI Speed Controller'];

    checks = struct();
    checks.solver_is_ode4 = strcmp( ...
        get_param(derivedModelName, 'Solver'), 'ode4');
    checks.solver_type_is_fixed_step = strcmp( ...
        get_param(derivedModelName, 'SolverType'), 'Fixed-step');
    checks.fixed_step_is_ts = strcmp( ...
        get_param(derivedModelName, 'FixedStep'), 'ts');
    checks.ts_is_00004 = parameters.ts == 0.0004;

    integrators = find_system(controllerPath, ...
        'LookUnderMasks', 'all', 'FollowLinks', 'on', ...
        'BlockType', 'Integrator');
    discreteIntegrators = find_system(controllerPath, ...
        'LookUnderMasks', 'all', 'FollowLinks', 'on', ...
        'BlockType', 'DiscreteIntegrator');
    checks.controller_integrator_is_continuous = ...
        numel(integrators) == 1 && isempty(discreteIntegrators);

    derivedSignatures = localCaptureFrozenSignatures(derivedModelName);
    checks.controller_parameters_equal_source = isequal( ...
        derivedSignatures.controller, sourceSignatures.controller);
    checks.plant_parameters_equal_source = isequal( ...
        derivedSignatures.plant, sourceSignatures.plant);
    checks.reference_conversion_equal_source = isequal( ...
        derivedSignatures.referenceConversion, ...
        sourceSignatures.referenceConversion);
    checks.speed_conversion_equal_source = isequal( ...
        derivedSignatures.speedConversion, sourceSignatures.speedConversion);

    checks.root_input_exists = localHasOneRootBlock( ...
        derivedModelName, 'Inport', 'SpeedRef_rps');
    checks.sampled_vcmd_output_exists = localHasOneRootBlock( ...
        derivedModelName, 'Outport', 'sampled_Vcmd');
    checks.sampled_speed_output_exists = localHasOneRootBlock( ...
        derivedModelName, 'Outport', 'sampled_MotorSpeed');

    vcmdZoh = [derivedModelName, '/Observe_Vcmd_ZOH'];
    speedZoh = [derivedModelName, '/Observe_MotorSpeed_ZOH'];
    checks.vcmd_observer_is_zoh = strcmp( ...
        get_param(vcmdZoh, 'BlockType'), 'ZeroOrderHold');
    checks.speed_observer_is_zoh = strcmp( ...
        get_param(speedZoh, 'BlockType'), 'ZeroOrderHold');
    checks.vcmd_zoh_sample_time_is_ts = strcmp( ...
        get_param(vcmdZoh, 'SampleTime'), 'ts');
    checks.speed_zoh_sample_time_is_ts = strcmp( ...
        get_param(speedZoh, 'SampleTime'), 'ts');

    checks.vcmd_observer_has_no_feedback = localOutputFeedsOnly( ...
        vcmdZoh, [derivedModelName, '/sampled_Vcmd']);
    checks.speed_observer_has_no_feedback = localOutputFeedsOnly( ...
        speedZoh, [derivedModelName, '/sampled_MotorSpeed']);

    checks.internal_stimulus_removed = ...
        isempty(find_system(derivedModelName, ...
            'SearchDepth', 1, 'BlockType', 'DiscretePulseGenerator')) && ...
        isempty(find_system(derivedModelName, ...
            'SearchDepth', 1, 'BlockType', 'ManualSwitch')) && ...
        isempty(find_system(derivedModelName, ...
            'SearchDepth', 1, 'BlockType', 'Constant'));
    checks.source_model_clean = strcmp( ...
        get_param(sourceModelName, 'Dirty'), 'off');
end

function signatures = localCaptureFrozenSignatures(modelName)
    controller = [modelName, '/PI Speed Controller'];
    signatures = struct();
    signatures.controller = struct( ...
        'Kps', get_param([controller, '/Gain1'], 'Gain'), ...
        'Kis', get_param([controller, '/Gain'], 'Gain'), ...
        'Kas', get_param([controller, '/Gain3'], 'Gain'), ...
        'VdcUpper', get_param([controller, '/Saturation'], 'UpperLimit'), ...
        'VdcLower', get_param([controller, '/Saturation'], 'LowerLimit'), ...
        'ErrorSumInputs', get_param([controller, '/Subtract'], 'Inputs'), ...
        'IntegratorType', get_param( ...
            [controller, '/Integrator'], 'BlockType'));
    signatures.plant = struct( ...
        'Numerator', get_param([modelName, '/Transfer Fcn2'], 'Numerator'), ...
        'Denominator', get_param([modelName, '/Transfer Fcn2'], 'Denominator'));
    signatures.referenceConversion = get_param( ...
        [modelName, '/Gain2'], 'Gain');
    signatures.speedConversion = get_param( ...
        [modelName, '/Gain4'], 'Gain');
end

function paths = localPaths(modelName)
    pulseBlocks = find_system(modelName, ...
        'SearchDepth', 1, 'BlockType', 'DiscretePulseGenerator');
    assert(numel(pulseBlocks) == 1, ...
        'build_sil_b2b_verification_model:UnexpectedPulseGeneratorCount', ...
        'Expected exactly one top-level DiscretePulseGenerator, found %d.', ...
        numel(pulseBlocks));
    paths = struct( ...
        'controller', [modelName, '/PI Speed Controller'], ...
        'constantOffset', [modelName, '/Constant2'], ...
        'pulseGenerator', pulseBlocks{1}, ...
        'referenceSubtract', [modelName, '/Subtract1'], ...
        'referenceMagnitudeGain', [modelName, '/Gain1'], ...
        'referenceSwitch', [modelName, '/Manual Switch'], ...
        'sineWave', [modelName, '/Sine Wave1'], ...
        'zeroConstant', [modelName, '/Constant3'], ...
        'waveformSwitch', [modelName, '/Manual Switch3']);
end

function tf = localHasOneRootBlock(modelName, blockType, blockName)
    blocks = find_system(modelName, ...
        'SearchDepth', 1, 'BlockType', blockType, 'Name', blockName);
    tf = numel(blocks) == 1;
end

function tf = localOutputFeedsOnly(sourceBlock, expectedDestination)
    portHandles = get_param(sourceBlock, 'PortHandles');
    assert(numel(portHandles.Outport) == 1, ...
        'Observation block must have exactly one output port: %s', ...
        sourceBlock);
    lineHandle = get_param(portHandles.Outport, 'Line');
    if lineHandle == -1
        tf = false;
        return;
    end
    destinationPorts = get_param(lineHandle, 'DstPortHandle');
    if numel(destinationPorts) ~= 1 || destinationPorts == -1
        tf = false;
        return;
    end
    destinationBlock = get_param(destinationPorts, 'Parent');
    tf = strcmp(getfullname(destinationBlock), expectedDestination) && ...
        strcmp(get_param(destinationBlock, 'BlockType'), 'Outport');
end

function localAssertFrozenParameterValues(parameters)
    expectedKps = (2 * pi * 40) / 2185.96;
    expectedKis = 17.76 * expectedKps;
    expectedKas = expectedKis / expectedKps;
    assert(parameters.ts == 0.0004, 'Unexpected ts value.');
    assert(parameters.Vdc == 12, 'Unexpected Vdc value.');
    assert(parameters.Kps == expectedKps, 'Unexpected Kps value.');
    assert(parameters.Kis == expectedKis, 'Unexpected Kis value.');
    assert(parameters.Kas == expectedKas, 'Unexpected Kas value.');
end

function localAssertSourceConfiguration(modelName, sampleTime)
    assert(strcmp(get_param(modelName, 'SolverType'), 'Fixed-step'), ...
        'Source SolverType must be Fixed-step.');
    assert(strcmp(get_param(modelName, 'Solver'), 'ode4'), ...
        'Source Solver must be ode4.');
    assert(strcmp(get_param(modelName, 'FixedStep'), 'ts'), ...
        'Source FixedStep must be ts.');
    assert(sampleTime == 0.0004, ...
        'Source ts must equal 0.0004 s.');
end

function localWriteManifest( ...
        manifestFile, protocolVersion, sourceFile, sourceHash, ...
        derivedFile, derivedModelName, parameters)
    fileIdentifier = fopen(manifestFile, 'wt');
    if fileIdentifier < 0
        error('build_sil_b2b_verification_model:ManifestOpenFailed', ...
            'Could not open manifest for writing: %s', manifestFile);
    end
    closeManifest = onCleanup(@() fclose(fileIdentifier));

    fprintf(fileIdentifier, 'Protocol version: %s\n', protocolVersion);
    fprintf(fileIdentifier, 'Source path: %s\n', sourceFile);
    fprintf(fileIdentifier, 'Source SHA-256: %s\n', sourceHash);
    fprintf(fileIdentifier, 'Derived path: %s\n', derivedFile);
    fprintf(fileIdentifier, 'MATLAB release: %s\n', version('-release'));
    fprintf(fileIdentifier, 'Solver: %s\n', ...
        get_param(derivedModelName, 'Solver'));
    fprintf(fileIdentifier, 'FixedStep: %s (ts = %.17g s)\n', ...
        get_param(derivedModelName, 'FixedStep'), parameters.ts);
    fprintf(fileIdentifier, 'Kps: %.17g\n', parameters.Kps);
    fprintf(fileIdentifier, 'Kis: %.17g\n', parameters.Kis);
    fprintf(fileIdentifier, 'Kas: %.17g\n', parameters.Kas);
    fprintf(fileIdentifier, 'Vdc: %.17g\n', parameters.Vdc);
    fprintf(fileIdentifier, 'ts: %.17g\n', parameters.ts);
    fprintf(fileIdentifier, ...
        'Observation block type: Zero-Order Hold\n');
    fprintf(fileIdentifier, ...
        'Observation sample time: ts = %.17g s\n', parameters.ts);
    fprintf(fileIdentifier, 'Root input: SpeedRef_rps\n');
    fprintf(fileIdentifier, ...
        'Root outputs: sampled_Vcmd, sampled_MotorSpeed\n');
    fprintf(fileIdentifier, ['Allowed transformations: externalize the ', ...
        'model-internal reference stimulus through discrete root input ', ...
        'SpeedRef_rps; retain the existing 2*pi conversion; add ', ...
        'observation-only Zero-Order Hold branches and sampled root ', ...
        'outputs for Vcmd and MotorSpeed.\n']);
    fprintf(fileIdentifier, 'Generation timestamp: %s\n', ...
        char(datetime('now', 'TimeZone', 'local', ...
        'Format', 'yyyy-MM-dd''T''HH:mm:ssXXX')));

    clear closeManifest;
end

function localAssertBlock(blockPath)
    assert(getSimulinkBlockHandle(blockPath) ~= -1, ...
        'build_sil_b2b_verification_model:MissingSourceBlock', ...
        'Expected source stimulus block not found: %s', blockPath);
end

function localAssertFile(filePath, description)
    assert(isfile(filePath), ...
        'build_sil_b2b_verification_model:MissingFile', ...
        '%s not found: %s', description, filePath);
end

function localEnsureDirectory(directoryPath)
    if ~isfolder(directoryPath)
        [created, message] = mkdir(directoryPath);
        assert(created, ...
            'build_sil_b2b_verification_model:DirectoryCreationFailed', ...
            'Could not create directory %s: %s', directoryPath, message);
    end
end

function hashValue = localFileSha256(filePath)
    fileIdentifier = fopen(filePath, 'rb');
    if fileIdentifier < 0
        error('build_sil_b2b_verification_model:HashFileOpenFailed', ...
            'Could not open file for hashing: %s', filePath);
    end
    closeFile = onCleanup(@() fclose(fileIdentifier));
    bytes = fread(fileIdentifier, Inf, '*uint8');
    clear closeFile;

    digest = java.security.MessageDigest.getInstance('SHA-256');
    digest.update(typecast(bytes(:), 'int8'));
    digestBytes = typecast(digest.digest(), 'uint8');
    hashValue = upper(string(reshape(dec2hex(digestBytes, 2).', 1, [])));
end

function localCloseCleanModelOpenedHere(modelName, modelWasLoaded)
    if modelWasLoaded || ~bdIsLoaded(modelName)
        return;
    end
    if strcmp(get_param(modelName, 'Dirty'), 'off')
        close_system(modelName, 0);
    else
        warning('build_sil_b2b_verification_model:SourceLeftOpen', ...
            ['Source model unexpectedly became dirty and was left open ', ...
             'without saving or discarding changes: %s'], modelName);
    end
end

function localRecoverIncompleteDerivedArtifact( ...
        modelName, derivedFile, manifestFile, sourceHash)
    hasDerivedFile = isfile(derivedFile);
    hasManifest = isfile(manifestFile);
    isUnmodifiedSourceCopy = hasDerivedFile && ...
        strcmpi(localFileSha256(derivedFile), sourceHash);

    if bdIsLoaded(modelName)
        assert(~hasManifest && isUnmodifiedSourceCopy, ...
            'build_sil_b2b_verification_model:ExistingDerivedLoaded', ...
            ['Derived model is already loaded and is not a recoverable ', ...
             'incomplete source copy: %s'], modelName);
        close_system(modelName, 0);
    end

    if hasDerivedFile || hasManifest
        assert(~hasManifest && isUnmodifiedSourceCopy, ...
            'build_sil_b2b_verification_model:ExistingDerivedArtifact', ...
            ['Existing derived artifacts are not a recoverable incomplete ', ...
             'source copy. Refusing to overwrite them.']);
        delete(derivedFile);
    end
end

function localCloseDerivedModel( ...
        modelName, derivedFile, manifestFile, sourceHash)
    if bdIsLoaded(modelName)
        if strcmp(get_param(modelName, 'Dirty'), 'off')
            close_system(modelName, 0);
        elseif ~isfile(manifestFile) && isfile(derivedFile) && ...
                strcmpi(localFileSha256(derivedFile), sourceHash)
            % A failed transformation can only discard an on-disk file
            % that is still byte-identical to the frozen source and has no
            % manifest. No completed derived artifact is overwritten.
            close_system(modelName, 0);
        else
            warning('build_sil_b2b_verification_model:DerivedLeftOpen', ...
                ['Derived model has unsaved changes and was left open for ', ...
                 'inspection: %s'], modelName);
            return;
        end
    end
    if ~isfile(manifestFile) && isfile(derivedFile) && ...
            strcmpi(localFileSha256(derivedFile), sourceHash)
        delete(derivedFile);
    end
end
