function resultTable = self_check_scalability_reversal_plan()
%SELF_CHECK_SCALABILITY_REVERSAL_PLAN Verify frozen zero-skip semantics.

    sequences = { ...
        [5, -5]; ...
        [5, 0, -5]; ...
        [-5, 0, 5]; ...
        [5, 5, 0, 0, -5, -5]; ...
        [-5, -5, 0, 0, 5, 5]; ...
        [6, -6, 6, -6]};
    expectedTargets = {2; 3; 3; 5; 5; [2, 3, 4]};
    expectedPrevious = {1; 1; 1; 2; 2; [1, 2, 3]};
    rows = repmat(struct('input_values',"", 'target_segments',"", ...
        'previous_nonzero_segments',"", 'status',""), numel(sequences), 1);

    for index = 1:numel(sequences)
        plan = scalability_reversal_plan(sequences{index});
        assert(isequal(plan.target_segments, expectedTargets{index}), ...
            'self_check_scalability_reversal_plan:TargetMismatch', ...
            'Unexpected reversal targets for %s.', mat2str(sequences{index}));
        assert(isequal(plan.previous_nonzero_segments, ...
            expectedPrevious{index}), ...
            'self_check_scalability_reversal_plan:PreconditionMismatch', ...
            'Unexpected previous nonzero plateau for %s.', ...
            mat2str(sequences{index}));
        rows(index).input_values = string(mat2str(sequences{index}));
        rows(index).target_segments = string(mat2str(plan.target_segments));
        rows(index).previous_nonzero_segments = string( ...
            mat2str(plan.previous_nonzero_segments));
        rows(index).status = "PASS";
    end
    resultTable = struct2table(rows);
    fprintf('Scalability reversal target self-check: PASS (%d/%d).\n', ...
        sum(resultTable.status == "PASS"), height(resultTable));
end
