function [resultTable, summary, detailData] = run_manual_mil_suite(varargin)
%RUN_MANUAL_MIL_SUITE Execute Manual Dynamic MIL Test Suite v1.0.
%
%   [RESULTTABLE, SUMMARY, DETAILDATA] = RUN_MANUAL_MIL_SUITE() executes
%   MTC-001 through MTC-005 against AS2308_MIL_Baseline_v3 and writes the
%   suite CSV files under the repository results directory.
%
%   RUN_MANUAL_MIL_SUITE('ModelName', MODELNAME) runs the same Test Cases
%   and existing Oracles against the selected model.
%
%   This runner introduces no new Test Case, requirement, threshold, or
%   Oracle. SUP-AW-001 and static configuration checks are outside this
%   dynamic compliance suite and are not included in its PASS/FAIL count.

    parser = inputParser;
    parser.FunctionName = mfilename;
    addParameter(parser, 'ModelName', 'AS2308_MIL_Baseline_v3', ...
        @(x) (ischar(x) && ~isempty(x)) || ...
        (isstring(x) && isscalar(x) && strlength(x) > 0));
    addParameter(parser, 'WriteResults', true, ...
        @(x) islogical(x) && isscalar(x));
    parse(parser, varargin{:});
    modelName = char(string(parser.Results.ModelName));
    writeResults = parser.Results.WriteResults;

    runnerDirectory = fileparts(mfilename('fullpath'));
    repositoryRoot = fileparts(runnerDirectory);
    modelDirectory = fullfile(repositoryRoot, 'model');
    oracleDirectory = fullfile(runnerDirectory, 'oracles');
    resultsDirectory = fullfile(repositoryRoot, 'results');
    modelFile = fullfile(modelDirectory, [modelName, '.slx']);
    parameterScript = fullfile( ...
        modelDirectory, 'AS2308_calculate_pi_control_cc.m');

    assert(isfile(modelFile), 'Model file not found: %s', modelFile);
    assert(isfile(parameterScript), ...
        'Parameter script not found: %s', parameterScript);
    assert(isfile(fullfile(oracleDirectory, 'evaluate_voltage_limit.m')), ...
        'Voltage Oracle not found in: %s', oracleDirectory);
    assert(isfile(fullfile(oracleDirectory, 'evaluate_tracking.m')), ...
        'Tracking Oracle not found in: %s', oracleDirectory);
    assert(isfile(fullfile(oracleDirectory, 'evaluate_direction.m')), ...
        'Direction Oracle not found in: %s', oracleDirectory);

    addpath(oracleDirectory);
    run(parameterScript);
    simulationVariables = struct( ...
        'ts', ts, 'Vdc', Vdc, 'Kps', Kps, 'Kis', Kis, 'Kas', Kas);

    modelWasLoaded = bdIsLoaded(modelName);
    load_system(modelFile);
    closeModel = onCleanup( ...
        @() localCloseModel(modelName, modelWasLoaded));

    % Execution preconditions for the persisted MIL baseline. These checks
    % do not override the model configuration.
    assert(strcmp(get_param(modelName, 'SolverType'), 'Fixed-step'), ...
        'Stored model SolverType must be Fixed-step.');
    assert(strcmp(get_param(modelName, 'Solver'), 'ode4'), ...
        'Stored model Solver must be ode4.');
    assert(strcmp(get_param(modelName, 'FixedStep'), 'ts'), ...
        'Stored model FixedStep must be ts.');
    assert(ts == 0.0004, 'Expected ts = 0.0004 s.');

    if ~isfolder(resultsDirectory)
        mkdir(resultsDirectory);
    end

    fprintf('\nManual Dynamic MIL Test Suite v1.0\n');
    fprintf('Model: %s\n', modelName);
    fprintf('Stored solver: Fixed-step / ode4 / ts (ts = %.7g s)\n\n', ts);

    % Constant-reference iterations use the same 1 s execution duration as
    % the existing tracking and voltage characterization runners. This is
    % a test execution parameter, not a new performance criterion.
    constantReferences = [16.75; -16.75; 2; -2; 15; -15];
    constantRuns = repmat(struct( ...
        'reference_rps', NaN, 'samples', table()), ...
        numel(constantReferences), 1);
    for runIndex = 1:numel(constantReferences)
        constantRuns(runIndex) = localRunConstantReference( ...
            modelName, simulationVariables, constantReferences(runIndex), 1);
    end

    %% MTC-001 -- Voltage Limit (REQ-VOLT-001)
    voltagePositive = evaluate_voltage_limit( ...
        constantRuns(1).samples.time_s, constantRuns(1).samples.Vcmd_v);
    voltageNegative = evaluate_voltage_limit( ...
        constantRuns(2).samples.time_s, constantRuns(2).samples.Vcmd_v);
    positiveRawLimitEvidence = ...
        any(constantRuns(1).samples.raw_pi_output_v > 12);
    negativeRawLimitEvidence = ...
        any(constantRuns(2).samples.raw_pi_output_v < -12);

    %% MTC-002 -- Low-Speed Constant Tracking (REQ-TRK-001)
    trackingPositive = evaluate_tracking( ...
        constantRuns(3).samples.time_s, ...
        constantRuns(3).samples.reference_rps, ...
        constantRuns(3).samples.motorspeed_rps);
    trackingNegative = evaluate_tracking( ...
        constantRuns(4).samples.time_s, ...
        constantRuns(4).samples.reference_rps, ...
        constantRuns(4).samples.motorspeed_rps);
    trackingPositiveClamp = localPersistentTerminalClamp( ...
        constantRuns(3).samples.time_s, ...
        constantRuns(3).samples.raw_pi_output_v, ...
        constantRuns(3).samples.Vcmd_v, Vdc, 0.05);
    trackingNegativeClamp = localPersistentTerminalClamp( ...
        constantRuns(4).samples.time_s, ...
        constantRuns(4).samples.raw_pi_output_v, ...
        constantRuns(4).samples.Vcmd_v, Vdc, 0.05);

    %% MTC-003 -- Bidirectional Direction (REQ-DIR-001)
    directionPositive = evaluate_direction( ...
        constantRuns(5).samples.time_s, ...
        constantRuns(5).samples.reference_rps, ...
        constantRuns(5).samples.motorspeed_rps);
    directionNegative = evaluate_direction( ...
        constantRuns(6).samples.time_s, ...
        constantRuns(6).samples.reference_rps, ...
        constantRuns(6).samples.motorspeed_rps);

    %% MTC-004 and MTC-005 -- reuse existing executable Test Case runners
    [singleReversalTable, singleReversalRunData] = ...
        run_single_reversal_test('ModelName', modelName);
    [repeatedSegmentTable, repeatedSummary, repeatedRunData] = ...
        run_repeated_reversal_test( ...
        'ModelName', modelName, 'PlateauDuration_s', 2, 'RepeatCount', 3);

    %% Build the nine top-level executable iteration records
    TestCaseID = [ ...
        "MTC-001"; "MTC-001"; ...
        "MTC-002"; "MTC-002"; ...
        "MTC-003"; "MTC-003"; ...
        "MTC-004"; "MTC-004"; ...
        "MTC-005"];
    IterationID = [ ...
        "IT-001"; "IT-002"; ...
        "IT-001"; "IT-002"; ...
        "IT-001"; "IT-002"; ...
        "IT-001"; "IT-002"; ...
        "IT-001"];
    RequirementID = [ ...
        "REQ-VOLT-001"; "REQ-VOLT-001"; ...
        "REQ-TRK-001"; "REQ-TRK-001"; ...
        "REQ-DIR-001"; "REQ-DIR-001"; ...
        "REQ-REV-001"; "REQ-REV-001"; ...
        "REQ-REV-001"];
    TestObjective = [ ...
        "Verify positive controller voltage limit"; ...
        "Verify negative controller voltage limit"; ...
        "Verify positive low-speed terminal tracking"; ...
        "Verify negative low-speed terminal tracking"; ...
        "Verify positive steady-state direction"; ...
        "Verify negative steady-state direction"; ...
        "Verify positive-to-negative single reversal"; ...
        "Verify negative-to-positive single reversal"; ...
        "Verify repeated bidirectional reversal"];
    TestInput = [ ...
        "+16.75 rps"; "-16.75 rps"; ...
        "+2 rps"; "-2 rps"; ...
        "+15 rps"; "-15 rps"; ...
        "+15 to -15 rps"; "-15 to +15 rps"; ...
        "+15/-15 rps, 2 s plateau, 3 repeats"];
    OracleUsed = [ ...
        "evaluate_voltage_limit"; "evaluate_voltage_limit"; ...
        "evaluate_tracking"; "evaluate_tracking"; ...
        "evaluate_direction"; "evaluate_direction"; ...
        "evaluate_direction + evaluate_tracking"; ...
        "evaluate_direction + evaluate_tracking"; ...
        "evaluate_direction + evaluate_tracking"];
    pass = [ ...
        voltagePositive.pass; voltageNegative.pass; ...
        trackingPositive.pass && ~trackingPositiveClamp; ...
        trackingNegative.pass && ~trackingNegativeClamp; ...
        directionPositive.pass; directionNegative.pass; ...
        singleReversalTable.overall_pass(1); ...
        singleReversalTable.overall_pass(2); ...
        repeatedSummary.overall_test_pass];
    Result = repmat("FAIL", 9, 1);
    Result(pass) = "PASS";
    if trackingPositiveClamp
        Result(3) = "INCONCLUSIVE_PRECONDITION";
    end
    if trackingNegativeClamp
        Result(4) = "INCONCLUSIVE_PRECONDITION";
    end
    Result(7:8) = singleReversalTable.status;
    Result(9) = repeatedSummary.overall_test_status;
    Applicability = repmat("NOT_REQUIRED", 9, 1);
    Applicability(3:4) = "APPLICABLE";
    if trackingPositiveClamp
        Applicability(3) = "PRECONDITION_NOT_MET";
    end
    if trackingNegativeClamp
        Applicability(4) = "PRECONDITION_NOT_MET";
    end
    ReversalSetup = repmat("NOT_REQUIRED", 9, 1);
    for reversalIndex = 1:2
        ReversalSetup(6 + reversalIndex) = localEstablishedText( ...
            singleReversalTable.setup_established(reversalIndex));
    end
    ReversalSetup(9) = localEstablishedText( ...
        repeatedSummary.initial_setup_established);
    KeyMetric = [ ...
        "max_vcmd_v"; "min_vcmd_v"; ...
        "max_abs_error_rps"; "max_abs_error_rps"; ...
        "direction_mismatch_sample_count"; ...
        "direction_mismatch_sample_count"; ...
        "tracking_max_abs_error_rps"; ...
        "tracking_max_abs_error_rps"; ...
        "passed_transition_count"];
    KeyMetricValue = [ ...
        voltagePositive.max_vcmd_v; voltageNegative.min_vcmd_v; ...
        trackingPositive.max_abs_error_rps; ...
        trackingNegative.max_abs_error_rps; ...
        directionPositive.mismatch_sample_count; ...
        directionNegative.mismatch_sample_count; ...
        singleReversalTable.tracking_max_abs_error_rps(1); ...
        singleReversalTable.tracking_max_abs_error_rps(2); ...
        repeatedSummary.passed_transition_count];
    Notes = strings(9, 1);
    Notes(1) = sprintf( ...
        'raw_pi_output > +12 V evidence: %s; max raw PI %.12g V', ...
            localTrueFalse(positiveRawLimitEvidence), ...
            max(constantRuns(1).samples.raw_pi_output_v));
    Notes(2) = sprintf( ...
        'raw_pi_output < -12 V evidence: %s; min raw PI %.12g V', ...
            localTrueFalse(negativeRawLimitEvidence), ...
            min(constantRuns(2).samples.raw_pi_output_v));
    Notes(3) = sprintf('window %.12g s; tolerance %.12g rps', ...
            trackingPositive.evaluation_window_s, ...
            trackingPositive.tolerance_rps);
    Notes(4) = sprintf('window %.12g s; tolerance %.12g rps', ...
            trackingNegative.evaluation_window_s, ...
            trackingNegative.tolerance_rps);
    Notes(5) = sprintf( ...
        'direction-only Oracle; reference direction %+d; motor direction %+d', ...
            directionPositive.reference_direction, ...
            directionPositive.motorspeed_direction);
    Notes(6) = sprintf( ...
        'direction-only Oracle; reference direction %+d; motor direction %+d', ...
            directionNegative.reference_direction, ...
            directionNegative.motorspeed_direction);
    Notes(7) = sprintf('direction %s; tracking %s; mismatches %d', ...
            localPassFail(singleReversalTable.direction_pass(1)), ...
            localPassFail(singleReversalTable.tracking_pass(1)), ...
            singleReversalTable.direction_mismatch_sample_count(1));
    Notes(8) = sprintf('direction %s; tracking %s; mismatches %d', ...
            localPassFail(singleReversalTable.direction_pass(2)), ...
            localPassFail(singleReversalTable.tracking_pass(2)), ...
            singleReversalTable.direction_mismatch_sample_count(2));
    Notes(9) = sprintf([ ...
        'setup %s; %d/%d required reversal transitions passed; ', ...
        '%d failed; %d inconclusive; segment details saved separately'], ...
            repeatedSummary.setup_status, ...
            repeatedSummary.passed_transition_count, ...
            repeatedSummary.required_transition_count, ...
            repeatedSummary.failed_transition_count, ...
            repeatedSummary.inconclusive_transition_count);

    resultTable = table( ...
        TestCaseID, IterationID, RequirementID, TestObjective, TestInput, ...
        OracleUsed, Result, Applicability, ReversalSetup, ...
        KeyMetric, KeyMetricValue, Notes);
    assert(height(resultTable) == 9, ...
        'Manual suite must contain exactly nine top-level executions.');
    assert(height(repeatedSegmentTable) == 6, ...
        'MTC-005 must preserve exactly six segment results.');

    passedExecutionCount = sum(Result == "PASS");
    failedExecutionCount = sum(Result == "FAIL");
    inconclusiveExecutionCount = sum( ...
        Result == "INCONCLUSIVE_PRECONDITION");
    executionErrorCount = sum(Result == "EXECUTION_ERROR");
    summary = struct( ...
        'suite_id', "Manual Dynamic MIL Test Suite v1.0", ...
        'model_name', string(modelName), ...
        'logical_test_case_count', 5, ...
        'top_level_execution_count', height(resultTable), ...
        'passed_execution_count', passedExecutionCount, ...
        'failed_execution_count', failedExecutionCount, ...
        'inconclusive_execution_count', inconclusiveExecutionCount, ...
        'execution_error_count', executionErrorCount, ...
        'overall_suite_pass', all(Result == "PASS"));
    summaryTable = struct2table(summary);

    resultsCsv = fullfile(resultsDirectory, 'manual_suite_v1_results.csv');
    summaryCsv = fullfile(resultsDirectory, 'manual_suite_v1_summary.csv');
    repeatedCsv = fullfile( ...
        resultsDirectory, 'manual_suite_v1_repeated_reversal_segments.csv');

    if writeResults
        % writetable consistently replaces existing files with the same names.
        writetable(resultTable, resultsCsv);
        writetable(summaryTable, summaryCsv);
        writetable(repeatedSegmentTable, repeatedCsv);
    end

    detailData = struct( ...
        'constant_runs', constantRuns, ...
        'single_reversal_results', singleReversalTable, ...
        'single_reversal_runs', singleReversalRunData, ...
        'repeated_reversal_segments', repeatedSegmentTable, ...
        'repeated_reversal_summary', repeatedSummary, ...
        'repeated_reversal_runs', repeatedRunData, ...
        'results_csv', string(resultsCsv), ...
        'summary_csv', string(summaryCsv), ...
        'repeated_segments_csv', string(repeatedCsv));

    fprintf('\nManual suite top-level results:\n');
    disp(resultTable);
    fprintf('Summary: %d/%d executions passed; overall suite %s\n', ...
        passedExecutionCount, height(resultTable), ...
        localPassFail(summary.overall_suite_pass));
    if writeResults
        fprintf('Results CSV: %s\n', resultsCsv);
        fprintf('Summary CSV: %s\n', summaryCsv);
        fprintf('MTC-005 segment CSV: %s\n', repeatedCsv);
    else
        fprintf('Result CSV writing: disabled\n');
    end
    clear closeModel;
end

function runResult = localRunConstantReference( ...
        modelName, simulationVariables, reference_rps, stopTime_s)
    simulationInput = Simulink.SimulationInput(modelName);
    variableNames = fieldnames(simulationVariables);
    for variableIndex = 1:numel(variableNames)
        variableName = variableNames{variableIndex};
        simulationInput = simulationInput.setVariable( ...
            variableName, simulationVariables.(variableName));
    end
    simulationInput = simulationInput.setVariable( ...
        'SpeedRef_cmd', reference_rps);
    simulationInput = simulationInput.setModelParameter( ...
        'StopTime', sprintf('%.17g', stopTime_s), ...
        'SignalLogging', 'on', ...
        'SignalLoggingName', 'logsout', ...
        'SignalLoggingSaveFormat', 'Dataset', ...
        'ReturnWorkspaceOutputs', 'on');

    simulationOutput = sim(simulationInput);
    loggedSignals = simulationOutput.get('logsout');
    referenceSignal = localGetLoggedSignal(loggedSignals, 'reference');
    motorSpeedSignal = localGetLoggedSignal(loggedSignals, 'motorspeed');
    rawPiSignal = localGetLoggedSignal(loggedSignals, 'raw_pi_output');
    vcmdSignal = localGetLoggedSignal(loggedSignals, 'Vcmd');

    time = double(motorSpeedSignal.Time(:));
    motorspeed = localSignalData(motorSpeedSignal);
    reference = localAlignSignal(referenceSignal, time);
    rawPiOutput = localAlignSignal(rawPiSignal, time);
    vcmd = localAlignSignal(vcmdSignal, time);

    runResult = struct( ...
        'reference_rps', reference_rps, ...
        'samples', table(time, reference, motorspeed, rawPiOutput, vcmd, ...
        'VariableNames', {'time_s', 'reference_rps', 'motorspeed_rps', ...
        'raw_pi_output_v', 'Vcmd_v'}));
end

function data = localSignalData(signal)
    data = double(squeeze(signal.Data));
    data = data(:);
end

function value = localAlignSignal(signal, targetTime)
    signalTime = double(signal.Time(:));
    signalData = localSignalData(signal);
    if isequal(signalTime, targetTime)
        value = signalData;
    else
        value = interp1( ...
            signalTime, signalData, targetTime, 'previous', 'extrap');
    end
end

function signal = localGetLoggedSignal(loggedSignals, signalName)
    signalElement = loggedSignals.get(signalName);
    if isempty(signalElement)
        error('run_manual_mil_suite:MissingSignal', ...
            'Logged signal "%s" was not found.', signalName);
    end
    signal = signalElement.Values;
end

function text = localPassFail(pass)
    if pass
        text = 'PASS';
    else
        text = 'FAIL';
    end
end

function text = localTrueFalse(value)
    if value
        text = 'true';
    else
        text = 'false';
    end
end

function text = localEstablishedText(value)
    if value
        text = "ESTABLISHED";
    else
        text = "NOT_ESTABLISHED";
    end
end

function persistentClamp = localPersistentTerminalClamp( ...
        time, rawPiOutput, vcmd, voltageLimit, evaluationWindow_s)
    rows = time >= time(end) - evaluationWindow_s;
    assert(any(rows), 'run_manual_mil_suite:EmptyApplicabilityWindow', ...
        'No samples were found in the Tracking applicability window.');
    terminalRawPi = rawPiOutput(rows);
    terminalVcmd = vcmd(rows);
    numericTolerance_v = 64 * eps(max([1; abs(terminalVcmd); voltageLimit]));
    positiveClamp = terminalRawPi > voltageLimit & ...
        abs(terminalVcmd - voltageLimit) <= numericTolerance_v;
    negativeClamp = terminalRawPi < -voltageLimit & ...
        abs(terminalVcmd + voltageLimit) <= numericTolerance_v;
    persistentClamp = all(positiveClamp | negativeClamp);
end

function localCloseModel(modelName, modelWasLoaded)
    if ~modelWasLoaded && bdIsLoaded(modelName)
        close_system(modelName, 0);
    end
end
