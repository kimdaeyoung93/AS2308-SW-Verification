function [executionTable, killMatrix, summaryTable, overall] = ...
        run_ai_mutation_analysis(varargin)
%RUN_AI_MUTATION_ANALYSIS Apply the frozen Primary Mutation Set to AI Suite v1.
%
%   [EXECUTIONS, KILLMATRIX, SUMMARY, OVERALL] =
%   RUN_AI_MUTATION_ANALYSIS() first reproduces the healthy 9/9 AI Suite
%   baseline and then executes the same frozen nine candidates for MUT-001
%   through MUT-006. A cell is a KILL only when a healthy PASS changes to
%   FAIL. INCONCLUSIVE_PRECONDITION and EXECUTION_ERROR are recorded but do
%   not count as kills.
%
%   RUN_AI_MUTATION_ANALYSIS('Execute', false) performs preflight only.
%
%   Mutations are applied only through Simulink.SimulationInput overrides.
%   The model on disk and the loaded baseline block parameters are not saved
%   or modified. No Manual Suite inputs or Manual mutation results are read.

    parser = inputParser;
    parser.FunctionName = mfilename;
    addParameter(parser, 'Execute', true, ...
        @(x) islogical(x) && isscalar(x));
    parse(parser, varargin{:});
    executeAnalysis = parser.Results.Execute;

    runnerDirectory = fileparts(mfilename('fullpath'));
    repositoryRoot = fileparts(runnerDirectory);
    modelName = 'AS2308_MIL_Baseline_v3';
    modelFile = fullfile(repositoryRoot, 'model', [modelName, '.slx']);
    mutationFile = fullfile(repositoryRoot, ...
        'mutations', '01_Mutation_Set.csv');
    specificationFile = fullfile(repositoryRoot, 'ai', 'output', ...
        'ai_suite_v1_resolved_execution_spec.csv');
    resultDirectory = fullfile(repositoryRoot, 'results', 'ai_mutation');

    localAssertFile(modelFile, 'Baseline model');
    localAssertFile(mutationFile, 'Frozen mutation definition');
    localAssertFile(specificationFile, 'Frozen AI execution specification');
    localAssertFile(fullfile(runnerDirectory, 'run_ai_mil_suite.m'), ...
        'AI MIL Suite runner');

    mutationOptions = detectImportOptions(mutationFile, 'TextType', 'string');
    mutationOptions = setvartype( ...
        mutationOptions, mutationOptions.VariableNames, 'string');
    mutationDefinitions = readtable(mutationFile, mutationOptions);
    localValidateMutationFile(mutationDefinitions);

    specificationOptions = detectImportOptions( ...
        specificationFile, 'TextType', 'string');
    specification = readtable(specificationFile, specificationOptions);
    assert(height(specification) == 9, ...
        'run_ai_mutation_analysis:UnexpectedCandidateCount', ...
        'The frozen AI Suite must contain exactly nine candidates.');

    if ~isfolder(resultDirectory)
        mkdir(resultDirectory);
    end
    assert(isfolder(resultDirectory), ...
        'run_ai_mutation_analysis:ResultDirectoryCreationFailed', ...
        'Could not create result directory: %s', resultDirectory);

    baselineKis = 17.76 * (2 * pi * 40 / 2185.96);
    Vdc = 12;
    modelWasLoaded = bdIsLoaded(modelName);
    load_system(modelFile);
    closeModel = onCleanup(@() localCloseModel(modelName, modelWasLoaded));
    assert(isa(closeModel, 'onCleanup'));
    baselineState = localCaptureBaselineState(modelName);
    modelFileBefore = dir(modelFile);
    for mutationIndex = 1:height(mutationDefinitions)
        localValidateMutationApplicability( ...
            modelName, baselineKis, Vdc, ...
            mutationDefinitions(mutationIndex, :));
    end
    localAssertBaselineState(modelName, baselineState);

    fprintf('\nOfficial AI MIL Suite v1 Mutation Analysis preflight\n');
    fprintf('Model: %s\n', modelName);
    fprintf('Frozen mutants: %d\n', height(mutationDefinitions));
    fprintf('Frozen AI executions per mutant: %d\n', height(specification));
    fprintf('Total mutant execution cells: %d\n', ...
        height(mutationDefinitions) * height(specification));
    fprintf('Output directory: %s\n', resultDirectory);
    run_ai_mil_suite('Execute', false, 'WriteResults', false);
    fprintf('Preflight: PASS\n');

    if ~executeAnalysis
        executionTable = table();
        killMatrix = table();
        summaryTable = table();
        overall = struct( ...
            'preflight_pass', true, ...
            'simulation_executed', false, ...
            'total_mutants', height(mutationDefinitions), ...
            'execution_count_per_mutant', height(specification));
        fprintf('Mutation simulations executed: false\n\n');
        return;
    end

    %% Consistency check: use the same analysis path with no mutation.
    fprintf('\nBaseline consistency check (no mutation)\n');
    [baselineResults, ~, ~] = run_ai_mil_suite( ...
        'MutationID', 'BASELINE', 'WriteResults', false);
    baselineResults = sortrows(baselineResults, 'selection_order');
    baselinePassCount = sum(baselineResults.status == "PASS");
    if height(baselineResults) ~= 9 || baselinePassCount ~= 9
        error('run_ai_mutation_analysis:BaselineConsistencyFailed', ...
            ['Baseline consistency check returned %d/9 PASS. ', ...
             'Mutation execution was not started.'], baselinePassCount);
    end
    assert(isequal(baselineResults.candidate_id, specification.candidate_id), ...
        'run_ai_mutation_analysis:BaselineCandidateMismatch', ...
        'Baseline candidate order does not match the frozen execution spec.');
    localAssertBaselineState(modelName, baselineState);
    fprintf('Baseline consistency: 9/9 PASS\n');

    mutantCount = height(mutationDefinitions);
    executionCount = height(baselineResults);
    totalRows = mutantCount * executionCount;
    executionRows = repmat(localEmptyExecutionRow(), totalRows, 1);
    killCell = false(mutantCount, executionCount);
    matrixStatus = strings(mutantCount, executionCount);
    summaryRows = repmat(localEmptySummaryRow(), mutantCount, 1);
    outputRow = 0;

    for mutationIndex = 1:mutantCount
        mutationID = mutationDefinitions.MutationID(mutationIndex);
        fprintf('\nMutation %d/%d: %s (%s)\n', mutationIndex, mutantCount, ...
            mutationID, mutationDefinitions.MutationName(mutationIndex));
        localAssertBaselineState(modelName, baselineState);

        [mutantResults, ~, ~] = run_ai_mil_suite( ...
            'MutationID', mutationID, 'WriteResults', false);
        mutantResults = sortrows(mutantResults, 'selection_order');
        assert(isequal(mutantResults.candidate_id, ...
            baselineResults.candidate_id), ...
            'run_ai_mutation_analysis:MutantCandidateMismatch', ...
            'Mutant %s did not execute the frozen candidates in order.', ...
            mutationID);

        for executionIndex = 1:executionCount
            outputRow = outputRow + 1;
            baselineRow = baselineResults(executionIndex, :);
            mutantRow = mutantResults(executionIndex, :);
            mutantStatus = mutantRow.status;
            killed = baselineRow.status == "PASS" && mutantStatus == "FAIL";
            killCell(mutationIndex, executionIndex) = killed;
            matrixStatus(mutationIndex, executionIndex) = ...
                localMatrixStatus(mutantStatus, killed);

            executionRows(outputRow) = struct( ...
                'mutation_id', mutationID, ...
                'mutation_name', mutationDefinitions.MutationName(mutationIndex), ...
                'candidate_id', mutantRow.candidate_id, ...
                'selection_order', mutantRow.selection_order, ...
                'requirement_id', mutantRow.requirement_id, ...
                'baseline_result', baselineRow.status, ...
                'mutant_result', mutantStatus, ...
                'killed_by_execution', killed, ...
                'kill_reason', localKillReason(mutantStatus, killed), ...
                'applicability', mutantRow.applicability, ...
                'failure_reason', mutantRow.failure_reason);
        end

        mutationKills = killCell(mutationIndex, :);
        firstKillIndex = find(mutationKills, 1, 'first');
        firstKillingCandidate = "";
        if ~isempty(firstKillIndex)
            firstKillingCandidate = ...
                baselineResults.candidate_id(firstKillIndex);
        end
        inconclusiveCount = sum( ...
            mutantResults.status == "INCONCLUSIVE_PRECONDITION");
        executionErrorCount = sum( ...
            mutantResults.status == "EXECUTION_ERROR");
        killed = any(mutationKills);
        assessmentStatus = "SURVIVED";
        if killed
            assessmentStatus = "KILLED";
        elseif inconclusiveCount > 0 || executionErrorCount > 0
            assessmentStatus = "UNRESOLVED";
        end
        summaryRows(mutationIndex) = struct( ...
            'mutant_id', mutationID, ...
            'mutant_description', ...
                mutationDefinitions.FaultDescription(mutationIndex), ...
            'killed', killed, ...
            'assessment_status', assessmentStatus, ...
            'first_killing_candidate', firstKillingCandidate, ...
            'killing_execution_count', sum(mutationKills), ...
            'total_execution_count', executionCount, ...
            'inconclusive_execution_count', inconclusiveCount, ...
            'execution_error_count', executionErrorCount, ...
            'total_mutants', NaN, ...
            'killed_mutants', NaN, ...
            'mutation_score_percent', NaN, ...
            'total_kill_cells', NaN, ...
            'total_execution_cells', NaN, ...
            'kill_density_percent', NaN);

        % SimulationInput overrides must leave the loaded and stored model
        % in the captured baseline configuration before the next mutant.
        localAssertBaselineState(modelName, baselineState);
    end

    totalMutants = mutantCount;
    killedMutants = sum([summaryRows.killed]);
    totalKillCells = sum(killCell, 'all');
    totalExecutionCells = mutantCount * executionCount;
    mutationScorePercent = 100 * killedMutants / totalMutants;
    killDensityPercent = 100 * totalKillCells / totalExecutionCells;
    for mutationIndex = 1:mutantCount
        summaryRows(mutationIndex).total_mutants = totalMutants;
        summaryRows(mutationIndex).killed_mutants = killedMutants;
        summaryRows(mutationIndex).mutation_score_percent = ...
            mutationScorePercent;
        summaryRows(mutationIndex).total_kill_cells = totalKillCells;
        summaryRows(mutationIndex).total_execution_cells = ...
            totalExecutionCells;
        summaryRows(mutationIndex).kill_density_percent = ...
            killDensityPercent;
    end

    executionTable = struct2table(executionRows);
    summaryTable = struct2table(summaryRows);
    matrixVariableNames = matlab.lang.makeValidName( ...
        cellstr(baselineResults.candidate_id), 'ReplacementStyle', 'underscore');
    killMatrix = array2table(matrixStatus, ...
        'VariableNames', matrixVariableNames);
    killMatrix = addvars(killMatrix, ...
        mutationDefinitions.MutationName, mutationDefinitions.MutationID, ...
        'Before', 1, 'NewVariableNames', {'mutation_name', 'mutation_id'});

    overall = struct( ...
        'baseline_passed_execution_count', baselinePassCount, ...
        'baseline_total_execution_count', executionCount, ...
        'total_mutants', totalMutants, ...
        'killed_mutants', killedMutants, ...
        'mutation_score_percent', mutationScorePercent, ...
        'total_kill_cells', totalKillCells, ...
        'total_execution_cells', totalExecutionCells, ...
        'kill_density_percent', killDensityPercent, ...
        'inconclusive_execution_count', ...
            sum(summaryTable.inconclusive_execution_count), ...
        'execution_error_count', ...
            sum(summaryTable.execution_error_count));

    executionFile = fullfile( ...
        resultDirectory, 'AI_Mutation_Execution_Results.csv');
    killMatrixFile = fullfile( ...
        resultDirectory, 'AI_Mutation_Kill_Matrix.csv');
    summaryFile = fullfile( ...
        resultDirectory, 'AI_Mutation_Summary.csv');
    writetable(executionTable, executionFile);
    writetable(killMatrix, killMatrixFile);
    writetable(summaryTable, summaryFile);

    localAssertBaselineState(modelName, baselineState);
    modelFileAfter = dir(modelFile);
    assert(modelFileBefore.bytes == modelFileAfter.bytes && ...
        modelFileBefore.datenum == modelFileAfter.datenum, ...
        'run_ai_mutation_analysis:ModelFileChanged', ...
        'The on-disk v3 model changed during runtime mutation analysis.');

    fprintf('\nAI Mutation Analysis result\n');
    disp(summaryTable(:, {'mutant_id', 'killed', ...
        'first_killing_candidate', 'killing_execution_count', ...
        'inconclusive_execution_count', 'execution_error_count'}));
    fprintf('Mutation score: %d/%d = %.12g%%\n', ...
        killedMutants, totalMutants, mutationScorePercent);
    fprintf('Kill density: %d/%d = %.12g%%\n', ...
        totalKillCells, totalExecutionCells, killDensityPercent);
    fprintf('Execution results: %s\n', executionFile);
    fprintf('Kill matrix: %s\n', killMatrixFile);
    fprintf('Summary: %s\n\n', summaryFile);
end

function row = localEmptyExecutionRow()
    row = struct( ...
        'mutation_id', "", ...
        'mutation_name', "", ...
        'candidate_id', "", ...
        'selection_order', NaN, ...
        'requirement_id', "", ...
        'baseline_result', "", ...
        'mutant_result', "", ...
        'killed_by_execution', false, ...
        'kill_reason', "", ...
        'applicability', "", ...
        'failure_reason', "");
end

function row = localEmptySummaryRow()
    row = struct( ...
        'mutant_id', "", ...
        'mutant_description', "", ...
        'killed', false, ...
        'assessment_status', "", ...
        'first_killing_candidate', "", ...
        'killing_execution_count', 0, ...
        'total_execution_count', 0, ...
        'inconclusive_execution_count', 0, ...
        'execution_error_count', 0, ...
        'total_mutants', NaN, ...
        'killed_mutants', NaN, ...
        'mutation_score_percent', NaN, ...
        'total_kill_cells', NaN, ...
        'total_execution_cells', NaN, ...
        'kill_density_percent', NaN);
end

function status = localMatrixStatus(mutantStatus, killed)
    if killed
        status = "KILL";
    elseif mutantStatus == "INCONCLUSIVE_PRECONDITION"
        status = "INCONCLUSIVE";
    elseif mutantStatus == "EXECUTION_ERROR"
        status = "ERROR";
    else
        status = "PASS";
    end
end

function reason = localKillReason(mutantStatus, killed)
    if killed
        reason = "OracleFailure";
    elseif mutantStatus == "INCONCLUSIVE_PRECONDITION"
        reason = "InconclusivePrecondition";
    elseif mutantStatus == "EXECUTION_ERROR"
        reason = "ExecutionError";
    else
        reason = "";
    end
end

function state = localCaptureBaselineState(modelName)
    state = struct( ...
        'integral_gain', get_param( ...
            [modelName, '/PI Speed Controller/Gain'], 'Gain'), ...
        'subtract_inputs', get_param( ...
            [modelName, '/PI Speed Controller/Subtract'], 'Inputs'), ...
        'upper_limit', get_param( ...
            [modelName, '/PI Speed Controller/Saturation'], 'UpperLimit'), ...
        'lower_limit', get_param( ...
            [modelName, '/PI Speed Controller/Saturation'], 'LowerLimit'));
end

function localAssertBaselineState(modelName, expected)
    actual = localCaptureBaselineState(modelName);
    assert(isequal(actual, expected), ...
        'run_ai_mutation_analysis:BaselineStateNotRestored', ...
        'Loaded model parameters were not restored to baseline state.');
end

function localValidateMutationApplicability( ...
        modelName, baselineKis, Vdc, mutation)
    gainPath = [modelName, '/PI Speed Controller/Gain'];
    subtractPath = [modelName, '/PI Speed Controller/Subtract'];
    saturationPath = [modelName, '/PI Speed Controller/Saturation'];
    mutationID = mutation.MutationID;
    switch mutationID
        case "MUT-001"
            assert(strcmp(get_param(gainPath, 'Gain'), 'Kis'));
            assert(isfinite(baselineKis) && baselineKis ~= 0);
            assert(mutation.MutatedValue == "0");
        case "MUT-002"
            assert(strcmp(get_param(gainPath, 'Gain'), 'Kis'));
            assert(isfinite(baselineKis) && baselineKis > 0);
            assert(mutation.MutatedValue == "-abs(Kis)");
        case "MUT-003"
            assert(strcmp(get_param(subtractPath, 'Inputs'), '+-'));
            assert(mutation.MutatedValue == "++");
        case "MUT-004"
            assert(strcmp(get_param(saturationPath, 'UpperLimit'), 'Vdc'));
            assert(Vdc == 12 && mutation.MutatedValue == "13");
        case "MUT-005"
            assert(strcmp(get_param(saturationPath, 'LowerLimit'), '-Vdc'));
            assert(Vdc == 12 && mutation.MutatedValue == "-13");
        case "MUT-006"
            assert(strcmp(get_param(saturationPath, 'UpperLimit'), 'Vdc'));
            assert(Vdc == 12 && mutation.MutatedValue == "0");
    end
end

function localValidateMutationFile(mutations)
    requiredColumns = [ ...
        "MutationID", "MutationName", "Target", "BaselineValue", ...
        "MutatedValue", "FaultDescription", "Status"];
    assert(all(ismember(requiredColumns, ...
        string(mutations.Properties.VariableNames))), ...
        'run_ai_mutation_analysis:InvalidMutationFile', ...
        'The frozen mutation file is missing required columns.');
    expectedIDs = compose("MUT-%03d", (1:6).');
    assert(height(mutations) == 6 && ...
        isequal(mutations.MutationID, expectedIDs), ...
        'run_ai_mutation_analysis:InvalidMutationSet', ...
        'The mutation set must contain exactly MUT-001 through MUT-006.');
    assert(all(mutations.Status == "Defined - Not Executed"), ...
        'run_ai_mutation_analysis:UnexpectedMutationStatus', ...
        'The frozen mutation definition Status changed unexpectedly.');
end

function localAssertFile(path, description)
    assert(isfile(path), 'run_ai_mutation_analysis:MissingDependency', ...
        '%s was not found: %s', description, path);
end

function localCloseModel(modelName, modelWasLoaded)
    if ~modelWasLoaded && bdIsLoaded(modelName)
        close_system(modelName, 0);
    end
end
